"""Generate MoonBit fixtures for the eight-short-window 3GPP psy path.

The C harness (_ref/aacenc/aac_ref.exe --short) runs FFmpeg 9.0.2's
`psy_3gpp_analyze_channel` with `num_windows = 8` (short band plan, short
bit-demand constants, per-window `w += 16` chains) on a deterministic spectrum
with a rotating attack ramp, and dumps the published `FFPsyBand` records in the
slot layout every consumer indexes with (`psy_bands[w*16+g]`).

Usage:
    bash _ref/aacenc/build.sh
    ./_ref/aacenc/aac_ref.exe --short > _ref/aacenc/vectors_short.txt
    python scripts/gen_aac_psy_short_vectors.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_ref", "aacenc", "vectors_short.txt")
DST = os.path.join(ROOT, "libavcodec", "aac_psy_vectors", "fixtures_short.mbt")

HEADER = """///|
/// AUTOGENERATED by scripts/gen_aac_psy_short_vectors.py from
/// _ref/aacenc/vectors_short.txt (FFmpeg 9.0.2 aacpsy.c, eight short windows).
/// Do not edit by hand.  Regenerate with:
///   bash _ref/aacenc/build.sh
///   ./aac_ref.exe --short > vectors_short.txt
///   python scripts/gen_aac_psy_short_vectors.py
///
/// {frames} frames of 1024 f32 MDCT coefficients analysed as 8 x 128 with
/// {bands} scalefactor bands per window.  `aac_psy_short_slot[f]` is the flat
/// `psy_bands[w * 16 + g]` index of each record, so the stride layout the port
/// publishes is compared against C's, not assumed.
"""


def parse():
    frames = []
    cur = None
    nb = 0
    with open(SRC, "r", encoding="ascii") as fh:
        for raw in fh:
            parts = raw.split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "FRAME":
                cur = {
                    "spec": [], "alloc": "0", "entropy": "0.0", "fill": "0",
                    "slot": [], "energy": [], "thr": [], "spread": [],
                    "bits": [],
                }
            elif tag == "SPEC":
                cur["spec"] = parts[2:]
            elif tag == "PSYALLOC":
                cur["alloc"] = parts[1]
                cur["entropy"] = parts[2]
                cur["fill"] = parts[3]
            elif tag == "SHORTCFG":
                nb = int(parts[2])
            elif tag == "PSYBAND":
                cur["slot"].append(parts[1])
                cur["energy"].append(parts[2])
                cur["thr"].append(parts[3])
                cur["spread"].append(parts[4])
                cur["bits"].append(parts[5])
            elif tag == "END":
                frames.append(cur)
                cur = None
    if not frames or nb == 0:
        raise SystemExit("no frames parsed from %s" % SRC)
    return frames, nb


def emit_matrix(name, cast, rows, per_line):
    """Array[Array[cast]] from a list of per-frame value lists."""
    out = ["///|", "pub let %s : Array[Array[%s]] = [" % (name, cast)]
    for row in rows:
        out.append("  [")
        for i in range(0, len(row), per_line):
            out.append("    %s," % ", ".join(row[i:i + per_line]))
        out.append("  ],")
    out.append("]")
    out.append("")
    return out


def emit_vector(name, cast, values, per_line):
    out = ["///|", "pub let %s : Array[%s] = [" % (name, cast)]
    for i in range(0, len(values), per_line):
        out.append("  %s," % ", ".join(values[i:i + per_line]))
    out.append("]")
    out.append("")
    return out


def main():
    frames, nb = parse()
    lines = [HEADER.format(frames=len(frames), bands=nb)]
    lines += emit_matrix("aac_psy_short_spec", "Double",
                         [f["spec"] for f in frames], 6)
    lines += emit_vector("aac_psy_short_alloc", "Int32",
                         [f["alloc"] for f in frames], 8)
    lines += emit_vector("aac_psy_short_entropy", "Double",
                         [f["entropy"] for f in frames], 4)
    lines += emit_vector("aac_psy_short_fill", "Int32",
                         [f["fill"] for f in frames], 8)
    for key, name, cast, per_line in (
        ("slot", "aac_psy_short_slot", "Int32", 14),
        ("energy", "aac_psy_short_energy", "Double", 4),
        ("thr", "aac_psy_short_threshold", "Double", 4),
        ("spread", "aac_psy_short_spread", "Double", 4),
        ("bits", "aac_psy_short_bits", "Int32", 8),
    ):
        lines += emit_matrix(name, cast, [f[key] for f in frames], per_line)

    body = "\n".join(lines)
    assert len(body) > 4000, "generated fixture is suspiciously short"
    tmp = DST + ".new"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    os.replace(tmp, DST)
    print("wrote %s (%d bytes, %d frames x %d bands, %d records)" % (
        DST, len(body), len(frames), nb, sum(len(f["slot"]) for f in frames)))


main()
