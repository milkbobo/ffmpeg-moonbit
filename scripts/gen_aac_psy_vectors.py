"""Generate MoonBit fixtures from _ref/aacenc/vectors.txt.

The C harness (_ref/aacenc/aac_ref.exe) runs FFmpeg 9.0.2's 3GPP psy model and
twoloop quantizer on a deterministic synthetic spectrum.  This script turns
its text dump into a MoonBit source file for the black-box regression package
libavcodec/aac_psy_vectors/.

Usage:
    python scripts/gen_aac_psy_vectors.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_ref", "aacenc", "vectors.txt")
DST = os.path.join(ROOT, "libavcodec", "aac_psy_vectors", "fixtures.mbt")


def parse():
    frames = []
    cur = None
    with open(SRC, "r", encoding="ascii") as fh:
        for raw in fh:
            parts = raw.split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "FRAME":
                cur = {
                    "spec": [],
                    "alloc": 0,
                    "entropy": 0.0,
                    "fill": 0,
                    "psy": [],
                    "two": [],
                }
            elif tag == "SPEC":
                cur["spec"] = [float(x) for x in parts[2:]]
            elif tag == "PSYALLOC":
                cur["alloc"] = int(parts[1])
                cur["entropy"] = float(parts[2])
                cur["fill"] = int(parts[3])
            elif tag == "PSYBAND":
                cur["psy"].append(
                    (
                        float(parts[2]),
                        float(parts[3]),
                        float(parts[4]),
                        int(parts[5]),
                    )
                )
            elif tag == "TWOBAND":
                cur["two"].append(
                    (
                        int(parts[2]),
                        int(parts[3]),
                        int(parts[4]),
                        float(parts[5]),
                    )
                )
            elif tag == "END":
                frames.append(cur)
                cur = None
    return frames


def fmt_double(v):
    return repr(v)


def emit_array(name, rows, conv, typ):
    out = ["///|", "pub let {} : Array[Array[{}]] = [".format(name, typ)]
    for row in rows:
        out.append("  [" + ", ".join(conv(v) for v in row) + "],")
    out.append("]")
    out.append("")
    return out


def main():
    frames = parse()
    assert len(frames) == 5, len(frames)
    for f in frames:
        assert len(f["spec"]) == 1024, len(f["spec"])
        assert len(f["psy"]) == 49, len(f["psy"])
        assert len(f["two"]) == 49, len(f["two"])

    lines = [
        "///|",
        "/// AUTOGENERATED by scripts/gen_aac_psy_vectors.py from",
        "/// _ref/aacenc/vectors.txt (FFmpeg 9.0.2 aacpsy.c + aaccoder.c).",
        "/// Do not edit by hand. Regenerate with:",
        "///   bash _ref/aacenc/build.sh && ./aac_ref.exe > vectors.txt",
        "///   python scripts/gen_aac_psy_vectors.py",
        "///",
        "/// 5 frames x 1024 f32 MDCT coefficients, 49 scalefactor bands each.",
        "/// The C side is f32 throughout; values here are the f32 values",
        "/// printed with %.9e and stored as Double for exact comparison.",
        "",
    ]

    # Spectral input, one array per frame.
    lines += emit_array(
        "aac_psy_spec", [f["spec"] for f in frames], fmt_double, "Double"
    )
    lines += emit_array(
        "aac_psy_ref_energy",
        [[b[0] for b in f["psy"]] for f in frames],
        fmt_double,
        "Double",
    )
    lines += emit_array(
        "aac_psy_ref_threshold",
        [[b[1] for b in f["psy"]] for f in frames],
        fmt_double,
        "Double",
    )
    lines += emit_array(
        "aac_psy_ref_spread",
        [[b[2] for b in f["psy"]] for f in frames],
        fmt_double,
        "Double",
    )
    lines += emit_array(
        "aac_psy_ref_bits",
        [[b[3] for b in f["psy"]] for f in frames],
        str,
        "Int32",
    )
    lines += emit_array(
        "aac_psy_ref_two_sf",
        [[b[0] for b in f["two"]] for f in frames],
        str,
        "Int32",
    )
    lines += emit_array(
        "aac_psy_ref_two_cb",
        [[b[1] for b in f["two"]] for f in frames],
        str,
        "Int32",
    )
    lines += emit_array(
        "aac_psy_ref_two_zeroes",
        [[b[2] for b in f["two"]] for f in frames],
        str,
        "Int32",
    )
    lines += emit_array(
        "aac_psy_ref_two_maxval",
        [[b[3] for b in f["two"]] for f in frames],
        fmt_double,
        "Double",
    )

    lines += [
        "///|",
        "pub let aac_psy_ref_alloc : Array[Int32] = ["
        + ", ".join(str(f["alloc"]) for f in frames)
        + "]",
        "",
        "///|",
        "pub let aac_psy_ref_entropy : Array[Double] = ["
        + ", ".join(fmt_double(f["entropy"]) for f in frames)
        + "]",
        "",
        "///|",
        "pub let aac_psy_ref_fill : Array[Int32] = ["
        + ", ".join(str(f["fill"]) for f in frames)
        + "]",
        "",
    ]

    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", DST, "frames=", len(frames), "bytes=", os.path.getsize(DST))


if __name__ == "__main__":
    main()
