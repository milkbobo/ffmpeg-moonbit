#!/usr/bin/env python3
"""Emit libavcodec/av1_kf_realdata_wbtest.mbt from the lossless AV1
keyframe vectors (.scratch/av1/ll128.ivf, ll160_multi.ivf) with reference
libdav1d framemd5 outputs."""

import base64
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
SCRATCH = os.path.join(HERE, '..', '.scratch', 'av1')
OUT = os.path.join(HERE, '..', 'libavcodec', 'av1_kf_realdata_wbtest.mbt')

STREAMS = [
    ('ll128', 'll128.ivf', 'll128.framemd5', 128, 96),
    ('ll160', 'll160_multi.ivf', 'll160_multi.framemd5', 160, 120),
]


def read_md5s(path):
    out = []
    for line in io.open(path):
        parts = line.strip().split(',')
        if len(parts) >= 5 and parts[0] == '0':
            out.append(parts[-1])
    return out


def main():
    parts = []
    parts.append('///|')
    parts.append('/// AV1 lossless keyframe vectors: all-intra libaom-av1')
    parts.append('/// streams (crf 0) decoded through the dav1d-derived')
    parts.append('/// software path and compared frame-by-frame against')
    parts.append('/// docker `linuxserver/ffmpeg:9.0.2` (libdav1d) framemd5.')
    parts.append('/// Generated by scripts/_gen_av1_kf_vectors.py; streams')
    parts.append('/// produced with `ffmpeg -f lavfi -i testsrc2=... -c:v')
    parts.append('/// libaom-av1 -crf 0 -cpu-used 8 [-g 1]`.')
    parts.append('')
    for name, ivf, md5file, w, h in STREAMS:
        data = open(os.path.join(SCRATCH, ivf), 'rb').read()
        md5s = read_md5s(os.path.join(SCRATCH, md5file))
        b64 = base64.b64encode(data).decode()
        parts.append('///|')
        parts.append('/// `%s`: %dx%d, %d frame(s).' % (name, w, h, len(md5s)))
        parts.append('let av1_kf_%s_b64 : Bytes = b"%s"' % (name, b64))
        parts.append('///|')
        parts.append('let av1_kf_%s_md5 : Array[String] = [' % name)
        for m in md5s:
            parts.append('  "%s",' % m)
        parts.append(']')
        parts.append('')
    body = io.open(os.path.join(HERE, '_av1_kf_test_body.tpl'), encoding='utf-8').read()
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(parts) + '\n' + body)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
