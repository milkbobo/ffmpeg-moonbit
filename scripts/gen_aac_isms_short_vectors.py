"""Generate MoonBit fixtures for the eight-short-window stereo pair of tools.

The C harness (_ref/aacenc/aac_ref.exe --isms) replays one stereo element per
frame through the full `aacenc.c:946-1000` element loop on the eight-window
shape: the sticky slot arrays carried across frames, mark_pns + twoloop +
search_for_pns per channel, then `ff_aac_search_for_is` + the intensity mix +
`search_for_ms`, all walking `w += group_len[w]`.  The spectra are a
phase-mixed pair (window-dependent correlation sign) so both intensity phases,
the flip variant and mid/side wins all fire.  Dumps: `PRE0/1` and
`STICKY0/1` pin the post-PNS state the stereo tools read (and the next frame
inherits), `ISDUMP`/`MSDUMP` pin the two searches' decisions at the
group-start slots.

Usage:
    bash _ref/aacenc/build.sh
    ./_ref/aacenc/aac_ref.exe --isms > _ref/aacenc/vectors_isms_short.txt
    python scripts/gen_aac_isms_short_vectors.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_ref", "aacenc", "vectors_isms_short.txt")
DST = os.path.join(
    ROOT, "libavcodec", "aac_is_vectors", "fixtures_short.mbt"
)

HEADER = """///|
/// AUTOGENERATED by scripts/gen_aac_isms_short_vectors.py from
/// _ref/aacenc/vectors_isms_short.txt (FFmpeg 9.0.2's search_for_is and
/// search_for_ms run on an eight-short-window stereo pair with the sticky
/// element arrays).  Do not edit by hand.  Regenerate with:
///   bash _ref/aacenc/build.sh
///   ./aac_ref.exe --isms > vectors_isms_short.txt
///   python scripts/gen_aac_isms_short_vectors.py
///
/// {frames} frames, each one stereo element on 8 windows x {bands} bands with
/// the grouping of `SHORTGRP`.  `isms_pre_*` is the post-PNS state both
/// searches read (group starts), `isms_sticky_*` the full 128-slot state the
/// next frame inherits, `isms_is_*`/`isms_ms_*` the two searches' decisions at
/// the group-start slots.
"""


def parse():
    frames = []
    cur = None
    nb = 0
    with open(SRC, "r", encoding="ascii") as fh:
        for raw in fh:
            parts = raw.split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "FRAME":
                cur = {
                    "spec0": [], "spec1": [], "alloc": "0", "group": [],
                    "slot": [], "pre0_sf": [], "pre0_bt": [], "pre0_z": [],
                    "pre1_sf": [], "pre1_bt": [], "pre1_z": [],
                    "is_mask": [], "is_ms": [], "is_bt": [],
                    "is_e0": [], "is_e1": [],
                    "ms_mask": [], "ms_sf0": [], "ms_cb0": [],
                    "ms_sf1": [], "ms_cb1": [],
                    "sticky0_sf": [], "sticky0_bt": [], "sticky0_z": [],
                    "sticky1_sf": [], "sticky1_bt": [], "sticky1_z": [],
                }
            elif tag == "SPEC0":
                cur["spec0"] = parts[2:]
            elif tag == "SPEC1":
                cur["spec1"] = parts[2:]
            elif tag == "PSYALLOC":
                cur["alloc"] = parts[1]
            elif tag == "SHORTCFG":
                nb = int(parts[2])
            elif tag == "SHORTGRP":
                cur["group"] = parts[1:9]
            elif tag.startswith("PRE"):
                ch = tag[3]
                if ch == "0":
                    cur["slot"].append(parts[1])
                cur["pre%s_sf" % ch].append(parts[2])
                cur["pre%s_bt" % ch].append(parts[3])
                cur["pre%s_z" % ch].append(parts[4])
            elif tag == "ISDUMP":
                # slot is_mask ms_mask bt1 ener0 ener1
                assert cur["slot"][len(cur["is_mask"])] == parts[1]
                cur["is_mask"].append(parts[2])
                cur["is_ms"].append(parts[3])
                cur["is_bt"].append(parts[4])
                cur["is_e0"].append(parts[5])
                cur["is_e1"].append(parts[6])
            elif tag == "MSDUMP":
                # slot ms_mask sf0 cb0 sf1 cb1
                idx = len(cur["ms_mask"])
                assert cur["slot"][idx] == parts[1], (idx, parts)
                cur["ms_mask"].append(parts[2])
                cur["ms_sf0"].append(parts[3])
                cur["ms_cb0"].append(parts[4])
                cur["ms_sf1"].append(parts[5])
                cur["ms_cb1"].append(parts[6])
            elif tag.startswith("STICKY"):
                ch = tag[6]
                cur["sticky%s_sf" % ch].append(parts[2])
                cur["sticky%s_bt" % ch].append(parts[3])
                cur["sticky%s_z" % ch].append(parts[4])
            elif tag == "END":
                assert len(cur["sticky0_sf"]) == 128
                assert len(cur["sticky1_sf"]) == 128
                frames.append(cur)
                cur = None
    if not frames or nb == 0:
        raise SystemExit("no frames parsed from %s" % SRC)
    return frames, nb


def emit_matrix(name, cast, rows, per_line):
    out = ["///|", "pub let %s : Array[Array[%s]] = [" % (name, cast)]
    for row in rows:
        out.append("  [")
        for i in range(0, len(row), per_line):
            out.append("    %s," % ", ".join(row[i:i + per_line]))
        out.append("  ],")
    out.append("]")
    out.append("")
    return out


def emit_vector(name, cast, values, per_line):
    out = ["///|", "pub let %s : Array[%s] = [" % (name, cast)]
    for i in range(0, len(values), per_line):
        out.append("  %s," % ", ".join(values[i:i + per_line]))
    out.append("]")
    out.append("")
    return out


def main():
    frames, nb = parse()
    lines = [HEADER.format(frames=len(frames), bands=nb)]
    lines += emit_matrix("aac_isms_spec0", "Double",
                         [f["spec0"] for f in frames], 6)
    lines += emit_matrix("aac_isms_spec1", "Double",
                         [f["spec1"] for f in frames], 6)
    lines += emit_vector("aac_isms_alloc", "Int32",
                         [f["alloc"] for f in frames], 8)
    lines += emit_matrix("aac_isms_group_len", "Int32",
                         [f["group"] for f in frames], 8)
    for key, name, cast, per_line in (
        ("slot", "aac_isms_slot", "Int32", 14),
        ("pre0_sf", "aac_isms_pre0_sf", "Int32", 14),
        ("pre0_bt", "aac_isms_pre0_bt", "Int32", 14),
        ("pre0_z", "aac_isms_pre0_z", "Int32", 14),
        ("pre1_sf", "aac_isms_pre1_sf", "Int32", 14),
        ("pre1_bt", "aac_isms_pre1_bt", "Int32", 14),
        ("pre1_z", "aac_isms_pre1_z", "Int32", 14),
        ("is_mask", "aac_isms_is_mask", "Int32", 14),
        ("is_ms", "aac_isms_is_ms", "Int32", 14),
        ("is_bt", "aac_isms_is_bt", "Int32", 14),
        ("is_e0", "aac_isms_is_e0", "Double", 4),
        ("is_e1", "aac_isms_is_e1", "Double", 4),
        ("ms_mask", "aac_isms_ms_mask", "Int32", 14),
        ("ms_sf0", "aac_isms_ms_sf0", "Int32", 14),
        ("ms_cb0", "aac_isms_ms_cb0", "Int32", 14),
        ("ms_sf1", "aac_isms_ms_sf1", "Int32", 14),
        ("ms_cb1", "aac_isms_ms_cb1", "Int32", 14),
        ("sticky0_sf", "aac_isms_sticky0_sf", "Int32", 16),
        ("sticky0_bt", "aac_isms_sticky0_bt", "Int32", 16),
        ("sticky0_z", "aac_isms_sticky0_z", "Int32", 16),
        ("sticky1_sf", "aac_isms_sticky1_sf", "Int32", 16),
        ("sticky1_bt", "aac_isms_sticky1_bt", "Int32", 16),
        ("sticky1_z", "aac_isms_sticky1_z", "Int32", 16),
    ):
        lines += emit_matrix(name, cast, [f[key] for f in frames], per_line)

    body = "\n".join(lines)
    assert len(body) > 4000, "generated fixture is suspiciously short"
    tmp = DST + ".new"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    os.replace(tmp, DST)
    print("wrote %s (%d bytes, %d frames, %d slot decisions)" % (
        DST, len(body), len(frames), sum(len(f["slot"]) for f in frames)))


main()
