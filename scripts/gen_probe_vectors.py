"""Generate the probe fixture package from .scratch/probe/*.

Reads the files produced by scripts/gen_probe_fixtures.sh (reference FFmpeg
9.0.2), truncates each to the window the test needs, and writes
libavformat/probe_vectors/fixtures.mbt as ASCII base64 constants.

Usage: python scripts/gen_probe_vectors.py
"""

import base64
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, ".scratch", "probe")
DST_DIR = os.path.join(ROOT, "libavformat", "probe_vectors")

# name -> (probe window bytes, ffprobe format_name)
CASES = [
    ("mp4", "p.mp4", 1 << 20, "mov,mp4,m4a,3gp,3g2,mj2"),
    ("mkv", "p.mkv", 512, "matroska,webm"),
    ("webm", "p.webm", 512, "matroska,webm"),
    ("ts", "p.ts", 1 << 20, "mpegts"),
    ("wav", "p.wav", 512, "wav"),
    ("flac", "p.flac", 512, "flac"),
    ("mp3", "p.mp3", 1 << 20, "mp3"),
    ("aac", "p.aac", 1 << 20, "aac"),
    ("ogg", "p.ogg", 512, "ogg"),
    ("ac3", "p.ac3", 8192, "ac3"),
    ("aiff", "p.aiff", 512, "aiff"),
    ("au", "p.au", 512, "au"),
    ("caf", "p.caf", 512, "caf"),
    ("asf", "p.asf", 512, "asf"),
    ("w64", "p.w64", 512, "w64"),
    ("png", "p.png", 1 << 20, "png_pipe"),
    ("mjpeg", "p.mjpeg", 1 << 20, "jpeg_pipe"),
]


def chunk(s, n=100):
    return [s[i:i + n] for i in range(0, len(s), n)]


def main():
    os.makedirs(DST_DIR, exist_ok=True)
    lines = []
    lines.append("///|")
    lines.append("/// Base64 fixtures for the format-probe tests. Generated by")
    lines.append("/// `scripts/gen_probe_vectors.py` from files produced by the reference")
    lines.append("/// FFmpeg 9.0.2 build (`scripts/gen_probe_fixtures.sh`); the expected")
    lines.append("/// `format_name` in each doc comment is `ffprobe -show_format` output.")
    lines.append("///")
    lines.append("/// Do not edit by hand.")
    lines.append("")
    meta = []
    for key, path, limit, fmt in CASES:
        full = os.path.join(SRC, path)
        with open(full, "rb") as f:
            raw = f.read()
        window = raw[:limit] if limit < len(raw) else raw
        b64 = base64.b64encode(window).decode("ascii")
        lines.append("///|")
        lines.append("/// `%s` (%d of %d bytes, ffprobe `%s`)." % (path, len(window), len(raw), fmt))
        parts = chunk(b64)
        expr = " +\n  ".join('b"%s"' % p for p in parts)
        lines.append('pub let probe_fixture_%s : Bytes = %s' % (key, expr))
        lines.append("")
        meta.append((key, fmt, len(window)))
    # Emit the case table so the test file stays in sync with the fixtures.
    lines.append("///|")
    lines.append("/// (fixture key, ffprobe `format_name`, window length).")
    lines.append("pub let probe_fixture_cases : Array[(String, String, Int)] = [")
    for key, fmt, n in meta:
        lines.append('  ("%s", "%s", %d),' % (key, fmt, n))
    lines.append("]")
    lines.append("")
    out = os.path.join(DST_DIR, "fixtures.mbt")
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", out)
    for key, fmt, n in meta:
        print("  %-6s %7d  %s" % (key, n, fmt))


if __name__ == "__main__":
    main()
