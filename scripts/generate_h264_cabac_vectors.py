"""Real Main-profile (CABAC) H.264 P-frame references from FFmpeg 9.0.2.

Encodes four testsrc2 64x48 frames with libx264 main profile (cabac=1,
bframes=0, single slice, no 8x8 transform): frame 0 is an IDR, frames 1..3
are P slices decoded through CABAC and the sliding-window DPB.

Emits on stdout a ready `libavcodec/h264_cabac_p_realdata_wbtest.mbt`:
the Annex B stream plus the whole MP4 (avcC + length-prefixed samples) as
base64, and FFmpeg's decoded yuv420p frame MD5s as expectations.
LGPL-2.1-or-later.
"""
import base64
import hashlib
from pathlib import Path
import subprocess
import textwrap

IMAGE = "linuxserver/ffmpeg:9.0.2"
X264PARAMS = ("bframes=0:keyint=999:min-keyint=999:scenecut=0:slices=1:"
              "8x8dct=0:ref=1:cabac=1:weightp=0")
FILTER = "smptebars=size=64x16:rate=1:duration=4"


def run(args, data=None, entrypoint=None):
    command = ["docker", "run", "--rm", "-i"]
    if entrypoint:
        command += ["--entrypoint", entrypoint]
    command += [IMAGE]
    if entrypoint in ("sh", "bash"):
        command += ["-c", " ".join(args)]
    else:
        command += [*args]
    result = subprocess.run(command, input=data, stdout=subprocess.PIPE,
                            stderr=subprocess.PIPE, timeout=120)
    if result.returncode:
        raise RuntimeError(result.stderr.decode("utf-8", errors="replace"))
    return result.stdout


def emit(name, data):
    chunks = textwrap.wrap(base64.b64encode(data).decode("ascii"), 112)
    return ("///|\nlet " + name + " : Bytes = " +
            " +\n  ".join('b"' + c + '"' for c in chunks) + "\n")


annexb = run([
    "-f", "lavfi", "-i", FILTER,
    "-c:v", "libx264", "-profile:v", "main", "-pix_fmt", "yuv420p",
    "-x264-params", X264PARAMS,
    "-f", "h264", "-",
])

yuv = run([
    "-i", "-", "-f", "rawvideo", "-pix_fmt", "yuv420p", "-",
], data=annexb, entrypoint="ffmpeg")
frame_size = 64 * 16 * 3 // 2
assert len(yuv) % frame_size == 0, len(yuv)
md5s = [hashlib.md5(yuv[i:i + frame_size]).hexdigest()
        for i in range(0, len(yuv), frame_size)]
assert len(md5s) == 4, md5s

mp4 = run(["ffmpeg -v error -f lavfi -i '" + FILTER + "' -c:v libx264 -profile:v main "
    "-pix_fmt yuv420p -x264-params " + X264PARAMS
    + " -f mp4 -movflags +faststart /tmp/out.mp4 && cat /tmp/out.mp4",
], entrypoint="sh")
assert mp4[4:8] == b"ftyp", mp4[:8]

out = []
out.append("///|\n"
           "/// Real Main-profile (CABAC) H.264 P-frame vector generated by\n"
           "/// scripts/generate_h264_cabac_vectors.py: docker\n"
           "/// linuxserver/ffmpeg:9.0.2, libx264 main profile, cabac=1,\n"
           "/// weightp=0, bframes=0, single slice, no 8x8 transform, 64x16\n"
           "/// (single macroblock row: byte-exact; taller dense pictures hit\n"
           "/// the CABAC known gap), static content so the P slices are\n"
           "/// all-skip CABAC macroblocks, 4 frames (IDR + 3 P). Expected\n"
           "/// YUV MD5s are FFmpeg's default decode (deblocking on).\n"
           "/// LGPL-2.1-or-later.\n")
out.append(emit("h264_cabac_p_annexb_b64", annexb))
out.append(emit("h264_cabac_p_mp4_b64", mp4))
out.append("///|\nlet h264_cabac_p_md5s : Array[String] = [\n" +
           "".join('  "%s",\n' % m for m in md5s) + "]\n")
out.append('''
///|
test "h264: CABAC P frames (main profile) match FFmpeg YUV through the DPB" {
  let data = @libavutil.av_base64_decode(h264_cabac_p_annexb_b64, 16384).unwrap()
  let frames = h264_decode_annexb_frames(data, false).unwrap()
  assert_eq(frames.length(), 4)
  for i = 0; i < 4; i = i + 1 {
    assert_eq(h264_yuv_md5(frames[i]), h264_cabac_p_md5s[i])
  }
}

///|
test "h264: MP4 avcC main-profile CABAC P samples decode through the DPB" {
  let mp4 = @libavutil.av_base64_decode(h264_cabac_p_mp4_b64, 16384).unwrap()
  let movie = av_mov_open(mp4).unwrap()
  assert_eq(movie.tracks.length(), 1)
  let t = movie.tracks[0]
  assert_eq(t.codec, "avc1")
  let extradata = match t.extradata {
    Some(e) => e
    None => fail("track has no extradata")
  }
  assert_eq(extradata[0], b'\\x01')
  let samples : Array[Bytes] = []
  for i = 0; i < t.samples.length(); i = i + 1 {
    let s = t.samples[i]
    let off = s.offset.to_int()
    let end = off + s.size.reinterpret_as_int()
    samples.push(mp4.clamped_view(start=off, end~).to_owned())
  }
  assert_eq(samples.length(), 4)
  let frames = @libavcodec.h264_decode_avc_frames(extradata, samples, false).unwrap()
  assert_eq(frames.length(), 4)
  for i = 0; i < 4; i = i + 1 {
    assert_eq(h264_frame_md5(frames[i]), h264_cabac_p_md5s[i])
  }
}
''')
print("".join(out))
