"""Generate MoonBit fixtures for the eight-short-window PNS pair of tools.

The C harness (_ref/aacenc/aac_ref.exe --pns --short) analyses a 1024-line LCG
spectrum as eight 128-sample windows, cycles the first five `window_grouping[]`
bytes, and runs the element-loop order of `aacenc.c:946-985` on the sticky
`SingleChannelElement` slot arrays: the `> RESERVED_BT` cleanup, `mark_pns`,
twoloop, then `search_for_pns` - whose per-window pricing reads the inner-window
slots earlier frames left behind.  The harness prints the slot decisions both
after twoloop (`TWOBAND`, group starts only) and after `search_for_pns` (`PNS`),
plus the full sticky arrays (`STICKY`), so the port's sticky model is compared
against C's instead of assumed.

Usage:
    bash _ref/aacenc/build.sh
    ./_ref/aacenc/aac_ref.exe --pns --short > _ref/aacenc/vectors_pns_short.txt
    python scripts/gen_aac_pns_short_vectors.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_ref", "aacenc", "vectors_pns_short.txt")
DST = os.path.join(
    ROOT, "libavcodec", "aac_pns_vectors", "fixtures_short.mbt"
)

HEADER = """///|
/// AUTOGENERATED by scripts/gen_aac_pns_short_vectors.py from
/// _ref/aacenc/vectors_pns_short.txt (FFmpeg 9.0.2 aaccoder.c's mark_pns and
/// search_for_pns run on eight short windows with the sticky element arrays).
/// Do not edit by hand.  Regenerate with:
///   bash _ref/aacenc/build.sh
///   ./aac_ref.exe --pns --short > vectors_pns_short.txt
///   python scripts/gen_aac_pns_short_vectors.py
///
/// {frames} frames, each analysed as 8 windows x {bands} scalefactor bands with
/// the window grouping of `SHORTGRP`, the sticky slot state of `STICKY` and
/// both tools' decisions on the group-start slots of `PNS` (`w * 16 + g`).
/// `pns_s_sticky_*` is the *end-of-frame* sticky state C's element carries
/// forward; the replay reproduces it frame by frame.
"""


def parse():
    frames = []
    cur = None
    nb = 0
    sticky = None
    with open(SRC, "r", encoding="ascii") as fh:
        for raw in fh:
            parts = raw.split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "FRAME":
                cur = {
                    "spec": [], "alloc": "0", "prev": "0", "group": [],
                    "slot": [], "two_sf": [], "two_cb": [], "two_z": [],
                    "can": [], "bt": [], "z": [], "ener": [],
                    "sticky_sf": [], "sticky_cb": [], "sticky_z": [],
                }
                sticky = None
            elif tag == "SPEC":
                cur["spec"] = parts[2:]
            elif tag == "PSYALLOC":
                cur["alloc"] = parts[1]
            elif tag == "SHORTCFG":
                nb = int(parts[2])
            elif tag == "SHORTGRP":
                cur["group"] = parts[1:9]
                cur["prev"] = str(len(frames) % 2)
            elif tag == "TWOBAND":
                cur["slot"].append(parts[1])
                cur["two_sf"].append(parts[2])
                cur["two_cb"].append(parts[3])
                cur["two_z"].append(parts[4])
            elif tag == "PNS":
                # slot can_pns band_type sf_idx zeroes pns_ener
                assert cur["slot"][len(cur["can"])] == parts[1]
                cur["can"].append(parts[2])
                cur["bt"].append(parts[3])
                cur["z"].append(parts[5])
                cur["ener"].append(parts[6])
            elif tag == "STICKY":
                # slot sf_idx band_type zeroes
                if sticky is None:
                    sticky = True
                cur["sticky_sf"].append(parts[2])
                cur["sticky_cb"].append(parts[3])
                cur["sticky_z"].append(parts[4])
            elif tag == "END":
                assert len(cur["sticky_sf"]) == 128, "STICKY block must cover all 128 slots"
                frames.append(cur)
                cur = None
    if not frames or nb == 0:
        raise SystemExit("no frames parsed from %s" % SRC)
    return frames, nb


def emit_matrix(name, cast, rows, per_line):
    out = ["///|", "pub let %s : Array[Array[%s]] = [" % (name, cast)]
    for row in rows:
        out.append("  [")
        for i in range(0, len(row), per_line):
            out.append("    %s," % ", ".join(row[i:i + per_line]))
        out.append("  ],")
    out.append("]")
    out.append("")
    return out


def emit_vector(name, cast, values, per_line):
    out = ["///|", "pub let %s : Array[%s] = [" % (name, cast)]
    for i in range(0, len(values), per_line):
        out.append("  %s," % ", ".join(values[i:i + per_line]))
    out.append("]")
    out.append("")
    return out


def main():
    frames, nb = parse()
    lines = [HEADER.format(frames=len(frames), bands=nb)]
    lines += emit_matrix("aac_pns_s_spec", "Double",
                         [f["spec"] for f in frames], 6)
    lines += emit_vector("aac_pns_s_prev", "Int32",
                         [f["prev"] for f in frames], 8)
    lines += emit_vector("aac_pns_s_alloc", "Int32",
                         [f["alloc"] for f in frames], 8)
    lines += emit_matrix("aac_pns_s_group_len", "Int32",
                         [f["group"] for f in frames], 8)
    for key, name, cast, per_line in (
        ("slot", "aac_pns_s_slot", "Int32", 14),
        ("two_sf", "aac_pns_s_two_sf", "Int32", 14),
        ("two_cb", "aac_pns_s_two_cb", "Int32", 14),
        ("two_z", "aac_pns_s_two_z", "Int32", 14),
        ("can", "aac_pns_s_can", "Int32", 14),
        ("bt", "aac_pns_s_bt", "Int32", 14),
        ("z", "aac_pns_s_z", "Int32", 14),
        ("ener", "aac_pns_s_ener", "Double", 4),
        ("sticky_sf", "aac_pns_s_sticky_sf", "Int32", 16),
        ("sticky_cb", "aac_pns_s_sticky_cb", "Int32", 16),
        ("sticky_z", "aac_pns_s_sticky_z", "Int32", 16),
    ):
        lines += emit_matrix(name, cast, [f[key] for f in frames], per_line)

    body = "\n".join(lines)
    assert len(body) > 4000, "generated fixture is suspiciously short"
    tmp = DST + ".new"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    os.replace(tmp, DST)
    print("wrote %s (%d bytes, %d frames, %d slot decisions)" % (
        DST, len(body), len(frames), sum(len(f["slot"]) for f in frames)))


main()
