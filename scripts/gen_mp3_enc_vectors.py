#!/usr/bin/env python3
"""Generate the MP3 (shine) encoder test fixtures from the C reference harness.

Reads `<ref>/v{1,2,3}.pcm` / `v{1,2,3}.mp3` produced by `_ref/shine/harness.exe`
(unmodified shine 3.1.1) and writes
`libavcodec/mp3_encode_vectors/fixtures.mbt` with base64 constants:

  - `mp3_vec{n}_pcm`  the int16le interleaved encoder input
  - `mp3_vec{n}_mp3`  the expected byte-exact encoder output

Usage: python scripts/gen_mp3_enc_vectors.py <ref_dir> <out.mbt>
"""
import base64
import sys

CONFIGS = [
    (1, "44100 Hz stereo 128 kbps (MPEG-1, padding-heavy)"),
    (2, "48000 Hz mono 192 kbps (MPEG-1 mono)"),
    (3, "22050 Hz mono 64 kbps (MPEG-2 LSF, single granule)"),
]

B64_WIDTH = 76


def b64_literal(name, doc, data):
    enc = base64.b64encode(data).decode("ascii")
    lines = [enc[i:i + B64_WIDTH] for i in range(0, len(enc), B64_WIDTH)]
    body = " +\n  ".join(f'b"{ln}"' for ln in lines)
    return f"///|\n/// {doc}\npub let {name} : Bytes = {body}\n"


def main():
    ref_dir, out_path = sys.argv[1], sys.argv[2]
    parts = [
        "/// Base64 fixtures for the MP3 (shine) encoder tests, generated by",
        "/// `scripts/gen_mp3_enc_vectors.py` from the compiled shine 3.1.1",
        "/// reference (`_ref/shine/harness.exe`, byte-identical to `shineenc`).",
        "///",
        "/// Do not edit by hand.",
        "",
    ]
    for idx, desc in CONFIGS:
        pcm = open(f"{ref_dir}/v{idx}.pcm", "rb").read()
        mp3 = open(f"{ref_dir}/v{idx}.mp3", "rb").read()
        parts.append(b64_literal(
            f"mp3_vec{idx}_pcm",
            f"v{idx}: {desc}, {len(pcm)} bytes of int16le interleaved PCM.",
            pcm))
        parts.append(b64_literal(
            f"mp3_vec{idx}_mp3",
            f"v{idx}: expected MP3 output, {len(mp3)} bytes.",
            mp3))
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(parts) + "\n")
    print(f"wrote {out_path}")
    for idx, _ in CONFIGS:
        pcm = open(f"{ref_dir}/v{idx}.pcm", "rb").read()
        mp3 = open(f"{ref_dir}/v{idx}.mp3", "rb").read()
        print(f"  v{idx}: pcm {len(pcm)} B, mp3 {len(mp3)} B")


if __name__ == "__main__":
    main()
