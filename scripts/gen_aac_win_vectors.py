#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Transcribe `_ref/aacenc/vectors_win.txt` (harness `--win`) into MoonBit
fixtures for `libavcodec/aac_win_vectors/`.

Input format (one block per (frame, channel); produced by `patch.py`'s
probes around `psy_lame_window`):

  WINCFG <frames> <kbps_per_ch> <threshold>
  FRAME <m> CH <c>
  WI <wt0> <wt1> <num_windows> <shape> <grp0..grp7>       (C's own window
                                                          state machine - not
                                                          ported, not emitted)
  RAW <att0..att8> <att_sum> <uselong> <grp_first> <wi_grp_pre> <prev_attack>

Only the integer decisions of the detector are transcribed: `attacks` after
the cascade, `att_sum` as the block-type decision reads it, `uselongblock`,
the first-attack index, the pre-overwrite `next_grouping` and the stored
`prev_attack`.  Regenerate with:

  bash _ref/aacenc/build.sh
  ./aac_ref.exe --win 26 > vectors_win.txt        (from _ref/aacenc)
  python scripts/gen_aac_win_vectors.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, os.pardir, "libavcodec", "aac_win_vectors", "fixtures.mbt")
SRC = os.path.join(HERE, os.pardir, "_ref", "aacenc", "vectors_win.txt")


def main():
    frames = None
    kbps = None
    threshold = None
    cur = None
    rows = []  # (frame, ch, raw[14])
    with open(SRC, "r", encoding="utf-8") as f:
        for line in f:
            parts = line.split()
            if not parts:
                continue
            if parts[0] == "WINCFG":
                frames, kbps, threshold = int(parts[1]), int(parts[2]), parts[3]
            elif parts[0] == "FRAME":
                cur = [int(parts[1]), int(parts[3])]
            elif parts[0] == "RAW":
                raw = [int(x) for x in parts[1:]]
                assert len(raw) == 14, raw
                rows.append((cur[0], cur[1], raw))
                cur = None
    assert frames is not None and len(rows) == frames * 2, (frames, len(rows))
    # stable order: frame-major, channel-minor
    rows.sort(key=lambda r: (r[0], r[1]))
    assert [(r[0], r[1]) for r in rows] == [
        (m, c) for m in range(frames) for c in range(2)
    ], "harness must emit both channels for every frame"

    def arr(name, vals, fmt):
        out = ["///|", "pub let %s : Array[%s] = [" % (name, fmt)]
        line = "  "
        for v in vals:
            tok = str(v).lower() if isinstance(v, bool) else str(v)
            if len(line) + len(tok) + 2 > 78:
                out.append(line.rstrip())
                line = "  "
            line += tok + ", "
        out.append(line.rstrip())
        out.append("]")
        return out

    lines = [
        "///|",
        "/// Window-decision golden vectors from `_ref/aacenc/vectors_win.txt`",
        "/// (FFmpeg 9.0.2 `psy_lame_window`, harness `--win`, %d frames x 2"
        % frames,
        "/// channels, %d kbps/ch, attack threshold %s).  Row index is"
        % (kbps, threshold),
        "/// `frame * 2 + ch`.  The PCM itself is regenerated by the test from",
        "/// the integer-exact LCG formula mirrored from the harness, so only",
        "/// the decisions are stored here.",
        "///",
        "/// Generated by scripts/gen_aac_win_vectors.py - do not edit.",
        "",
    ]
    lines += arr("aac_win_attacks", [r[2][0:9] for r in rows], "Array[Int]")
    lines.append("")
    lines += arr("aac_win_att_sum", [r[2][9] for r in rows], "Int")
    lines.append("")
    lines += arr("aac_win_uselong", [r[2][10] != 0 for r in rows], "Bool")
    lines.append("")
    lines += arr("aac_win_grp_first", [r[2][11] for r in rows], "Int")
    lines.append("")
    lines += arr("aac_win_wi_grp_pre", [r[2][12] for r in rows], "Int")
    lines.append("")
    lines += arr("aac_win_prev_attack", [r[2][13] for r in rows], "Int")
    lines.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.normpath(OUT), "(%d rows)" % len(rows))


if __name__ == "__main__":
    sys.exit(main())
