#!/usr/bin/env python3
"""Generate `libavcodec/opus_encode_vectors/fixtures.mbt` from the patched
FFmpeg 9.0.2 Opus encoder reference harness.

The harness (`_ref/opus/opus_ref_harness.exe`) feeds a deterministic
three-tone + LCG-dither programme into the patched encoder and writes:
  * `<out>.pcm`  planar f32le PCM (all channels concatenated, `frames*960`
                 samples per channel),
  * `<out>.pkt`  the packets, each prefixed with a little-endian u32 length.

Both are turned into MoonBit literals here: the PCM samples become decimal
strings (Python `repr` of the f32 value round-trips binary32 exactly) and the
packet stream becomes one hex string (length prefixes dropped).

Usage:
    python scripts/gen_opus_enc_vectors.py _ref/opus
"""

import io
import os
import struct
import subprocess
import sys

FRAMES = 12
VECTORS = [
    # (name, channels, bit_rate, frames)
    ("v1", 2, 96000, FRAMES),
    ("v2", 1, 48000, FRAMES),
]

HEADER = '''/// Fixtures for the Opus encoder tests, generated by the patched
/// FFmpeg 9.0.2 reference harness (`_ref/opus/opus_ref_harness.exe`,
/// see `scripts/gen_opus_enc_vectors.py`).
/// `opus_vec{n}_pcm[ch]` holds channel ch's f32 input as decimal string
/// literals (repr round-trips binary32 exactly), 960 samples per frame,
/// 12 frames. `opus_vec{n}_pkt` holds the expected byte-exact packets
/// as hex (concatenated).
///
/// Do not edit by hand.
'''


def run_harness(ref_dir, name, channels, bit_rate, frames):
    pkt = os.path.join(ref_dir, name + ".pkt")
    subprocess.run(
        [os.path.join(ref_dir, "opus_ref_harness.exe"),
         str(frames), str(channels), str(bit_rate), pkt],
        check=True, stdout=subprocess.DEVNULL,
    )
    return pkt, pkt + ".pcm"


def read_packets(path):
    data = io.open(path, "rb").read()
    out, i = [], 0
    while i < len(data):
        (n,) = struct.unpack_from("<I", data, i)
        i += 4
        out.append(data[i:i + n])
        i += n
    assert i == len(data)
    return out


def read_planes(path, channels):
    data = io.open(path, "rb").read()
    total = len(data) // 4
    vals = struct.unpack("<%df" % total, data)
    per = total // channels
    return [vals[c * per:(c + 1) * per] for c in range(channels)]


def emit_pcm(name, planes):
    out = []
    out.append("///|")
    out.append("/// %s: 48 kHz %s %d kbps, f32 planar PCM (%d ch, %d samples/ch)."
               % (name, "stereo" if len(planes) == 2 else "mono",
                  0, len(planes), len(planes[0])))
    out.append("pub let opus_vec%s_pcm : Array[Array[String]] = [" % name[1:])
    for plane in planes:
        out.append("  [")
        line = []
        for i, v in enumerate(plane):
            line.append('"%s",' % repr(v))
            if len(line) == 8:
                out.append("    " + " ".join(line))
                line = []
        if line:
            out.append("    " + " ".join(line))
        out.append("  ],")
    out.append("]")
    return "\n".join(out)


def emit_pkt(name, packets):
    blob = b"".join(packets)
    hexs = blob.hex()
    out = ["///|",
           "/// %s: expected packets, %d packets, %d bytes."
           % (name, len(packets), len(blob)),
           'pub let opus_vec%s_pkt : String = ' % name[1:]]
    chunks = [hexs[i:i + 96] for i in range(0, len(hexs), 96)]
    for i, c in enumerate(chunks):
        sep = " +" if i + 1 < len(chunks) else ""
        out.append('  "%s"%s' % (c, sep))
    return "\n".join(out)


def main():
    ref_dir = sys.argv[1] if len(sys.argv) > 1 else "_ref/opus"
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    dst = os.path.join(root, "libavcodec", "opus_encode_vectors", "fixtures.mbt")

    body = [HEADER]
    for name, channels, bit_rate, frames in VECTORS:
        pkt, pcm = run_harness(ref_dir, name, channels, bit_rate, frames)
        packets = read_packets(pkt)
        planes = read_planes(pcm, channels)
        body.append("")
        body.append(emit_pcm(name, planes))
        body.append(emit_pkt(name, packets))
        print("%s: %d packets, %d bytes, %d samples/ch"
              % (name, len(packets), sum(len(p) for p in packets), len(planes[0])))

    io.open(dst, "w", encoding="utf-8", newline="\n").write("\n".join(body) + "\n")
    print("wrote", dst)


if __name__ == "__main__":
    main()
