"""Generate libavcodec/wma_tables.mbt from the FFmpeg 9.0.2 WMA sources.

Run from the moonbit/ directory:
    python scripts/_gen_wma_tables.py
The FFmpeg tree is expected at ../.scratch/FFmpeg-n9.0.2 (repository scratch).
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, ".scratch", "FFmpeg-n9.0.2", "libavcodec")
OUT = os.path.join(ROOT, "libavcodec", "wma_tables.mbt")


def read(name):
    with open(os.path.join(SRC, name), "r", encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def extract_block(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^=;]*=\s*\{", text)
    if not m:
        raise SystemExit("array not found: " + name)
    i = m.end() - 1
    depth = 0
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[m.end():i]
        i += 1
    raise SystemExit("unterminated array: " + name)


def numbers(block):
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|-?\d+", block)]


def floats(block):
    return [float(x) for x in re.findall(
        r"-?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?", block)]


def split_rows(block):
    out = []
    depth = 0
    start = None
    for i, c in enumerate(block):
        if c == "{":
            if depth == 0:
                start = i + 1
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                out.append(block[start:i])
    return out


def rows(block):
    return [numbers(r) for r in split_rows(block)]


def rows_float(block):
    return [floats(r) for r in split_rows(block)]


def fmt_int(values, indent="  ", width=100):
    lines = []
    cur = indent
    for v in values:
        add = str(v) + ", "
        if len(cur) + len(add) > width:
            lines.append(cur.rstrip())
            cur = indent + add
        else:
            cur += add
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def fmt_uint(values, indent="  ", width=100):
    lines = []
    cur = indent
    for v in values:
        add = str(v) + "U, "
        if len(cur) + len(add) > width:
            lines.append(cur.rstrip())
            cur = indent + add
        else:
            cur += add
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def fmt_float(values, indent="  ", width=96):
    lines = []
    cur = indent
    for v in values:
        add = repr(float(v)) + ", "
        if len(cur) + len(add) > width:
            lines.append(cur.rstrip())
            cur = indent + add
        else:
            cur += add
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def emit_int(name, values, comment):
    return "///|\n/// %s\nlet %s : FixedArray[Int32] = [\n%s\n]\n" % (
        comment, name, fmt_int(values))


def emit_uint(name, values, comment):
    return "///|\n/// %s\nlet %s : FixedArray[UInt32] = [\n%s\n]\n" % (
        comment, name, fmt_uint(values))


def emit_float(name, values, comment):
    return "///|\n/// %s\nlet %s : FixedArray[Double] = [\n%s\n]\n" % (
        comment, name, fmt_float(values))


def emit_2d_int(name, rws, comment):
    body = []
    for row in rws:
        body.append("  [" + ", ".join(str(v) for v in row) + "]")
    return "///|\n/// %s\nlet %s : Array[FixedArray[Int32]] = [\n%s\n]\n" % (
        comment, name, ",\n".join(body))


def emit_2d_float(name, rws, comment):
    body = []
    for row in rws:
        body.append("  [" + ", ".join(repr(float(v)) for v in row) + "]")
    return "///|\n/// %s\nlet %s : Array[FixedArray[Double]] = [\n%s\n]\n" % (
        comment, name, ",\n".join(body))


wmadata = read("wmadata.h")
freqs = read("wma_freqs.c")

parts = ["""///|
/// WMA v1/v2 tables extracted from FFmpeg 9.0.2 `libavcodec/wmadata.h` and
/// `wma_freqs.c`; generated by `scripts/_gen_wma_tables.py`.
///
/// Original FFmpeg code is LGPL-2.1-or-later; this port keeps the same license.
"""]

parts.append(emit_int("wma_critical_freqs", numbers(extract_block(freqs, "ff_wma_critical_freqs")),
                      "`ff_wma_critical_freqs` (25 Bark-edge frequencies)."))

for name in ["exponent_band_22050", "exponent_band_32000", "exponent_band_44100"]:
    parts.append(emit_2d_int("wma_" + name,
                             rows(extract_block(wmadata, name)),
                             "`%s[3][25]`: first entry is the band count." % name))

parts.append(emit_2d_int("wma_hgain_hufftab",
                         rows(extract_block(wmadata, "ff_wma_hgain_hufftab")),
                         "`ff_wma_hgain_hufftab[37][2]`: code, bits (symbol - 18)."))
parts.append(emit_2d_float("wma_lsp_codebook",
                           rows_float(extract_block(wmadata, "ff_wma_lsp_codebook")),
                           "`ff_wma_lsp_codebook[NB_LSP_COEFS][16]`."))

for i in range(6):
    codes = numbers(extract_block(wmadata, "coef%d_huffcodes" % i))
    bits = numbers(extract_block(wmadata, "coef%d_huffbits" % i))
    levels = numbers(extract_block(wmadata, "levels%d" % i))
    assert len(codes) == len(bits), (i, len(codes), len(bits))
    parts.append(emit_uint("wma_coef%d_codes" % i, codes,
                           "`coef%d_huffcodes`." % i))
    parts.append(emit_int("wma_coef%d_bits" % i, bits, "`coef%d_huffbits`." % i))
    parts.append(emit_int("wma_coef%d_levels" % i, levels,
                          "`levels%d`: run lengths per level." % i))

text = "\n".join(parts)
assert len(text) > 20000
with open(OUT + ".new", "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
os.replace(OUT + ".new", OUT)
print("wrote", OUT, len(text), "bytes")
print("sizes", [len(numbers(extract_block(wmadata, "coef%d_huffcodes" % i))) for i in range(6)])
