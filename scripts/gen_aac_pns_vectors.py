"""Generate the `aac_pns_vectors` fixture from the C `mark_pns` reference.

Runs `_ref/aacenc/aac_ref.exe --pns` (FFmpeg 9.0.2 `aaccoder.c` `mark_pns` on an
LCG-noise spectrum) and writes the MoonBit fixture package consumed by
`libavcodec/aac_pns_vectors/`.

    bash _ref/aacenc/build.sh
    python scripts/gen_aac_pns_vectors.py

The noise spectrum is needed because PNS only fires on noise-like bands (the psy
model must report `spread >= spread_threshold`, 0.75 at lambda 120); the tonal
synthetic spectrum of the default harness mode never gets there.
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
REF = os.path.join(REPO, "_ref", "aacenc", "aac_ref.exe")
OUT_DIR = os.path.join(REPO, "libavcodec", "aac_pns_vectors")
NFRAMES = 5
NSPEC = 1024
NBANDS = 49


def run():
    res = subprocess.run(
        [REF, "--pns"], capture_output=True, text=True, cwd=os.path.dirname(REF)
    )
    if res.returncode != 0:
        sys.exit("reference failed: " + res.stderr[-2000:])
    return res.stdout.splitlines()


def parse(lines):
    specs, cans, eners = [], [], []
    sfs, cbs, zeros = [], [], []
    final_bt, final_sf, final_zero, final_ener = [], [], [], []
    cur_spec = None
    cur_can = None
    cur_ener = None
    cur_sf, cur_cb, cur_zero = None, None, None
    cur_fbt, cur_fsf, cur_fzero, cur_fener = None, None, None, None
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "SPEC":
            cur_spec = [float(v) for v in parts[2:]]
            if len(cur_spec) != NSPEC:
                sys.exit("short SPEC: %d" % len(cur_spec))
        elif parts[0] == "PSNMARK":
            if cur_can is None:
                cur_can, cur_ener = [], []
            cur_can.append(int(parts[2]))
            cur_ener.append(float(parts[3]))
        elif parts[0] == "TWOBAND":
            if cur_sf is None:
                cur_sf, cur_cb, cur_zero = [], [], []
            cur_sf.append(int(parts[2]))
            cur_cb.append(int(parts[3]))
            cur_zero.append(int(parts[4]))
        elif parts[0] == "PNSFINAL":
            if cur_fbt is None:
                cur_fbt, cur_fsf, cur_fzero, cur_fener = [], [], [], []
            cur_fbt.append(int(parts[2]))
            cur_fsf.append(int(parts[3]))
            cur_fzero.append(int(parts[4]))
            cur_fener.append(float(parts[5]))
        elif parts[0] == "END":
            if (cur_spec is None or cur_can is None or cur_sf is None
                    or cur_fbt is None):
                sys.exit("incomplete frame")
            specs.append(cur_spec)
            cans.append(cur_can)
            eners.append(cur_ener)
            sfs.append(cur_sf)
            cbs.append(cur_cb)
            zeros.append(cur_zero)
            final_bt.append(cur_fbt)
            final_sf.append(cur_fsf)
            final_zero.append(cur_fzero)
            final_ener.append(cur_fener)
            cur_spec = cur_can = cur_ener = None
            cur_sf, cur_cb, cur_zero = None, None, None
            cur_fbt, cur_fsf, cur_fzero, cur_fener = None, None, None, None
    if len(specs) != NFRAMES:
        sys.exit("expected %d frames, got %d" % (NFRAMES, len(specs)))
    for rows, name in (
        (cans, "can"), (sfs, "sf"), (cbs, "cb"), (zeros, "zero"),
        (final_bt, "final_bt"), (final_sf, "final_sf"),
        (final_zero, "final_zero"), (final_ener, "final_ener"),
    ):
        for row in rows:
            if len(row) != NBANDS:
                sys.exit("%s: expected %d bands, got %d" % (name, NBANDS, len(row)))
    return (specs, cans, eners, sfs, cbs, zeros,
            final_bt, final_sf, final_zero, final_ener)


def fmt_double(v):
    return repr(float(v))


def fmt_array(rows, conv):
    out = []
    for row in rows:
        out.append("  [" + ", ".join(conv(v) for v in row) + "],")
    return "\n".join(out)


def main():
    lines = run()
    (specs, cans, eners, sfs, cbs, zeros,
     final_bt, final_sf, final_zero, final_ener) = parse(lines)
    os.makedirs(OUT_DIR, exist_ok=True)

    header = (
        "///|\n"
        "/// AUTOGENERATED by scripts/gen_aac_pns_vectors.py from\n"
        "/// `_ref/aacenc/aac_ref.exe --pns` (FFmpeg 9.0.2 `aaccoder.c` `mark_pns`).\n"
        "/// Do not edit by hand. Regenerate with:\n"
        "///   bash _ref/aacenc/build.sh\n"
        "///   python scripts/gen_aac_pns_vectors.py\n"
        "///\n"
        "/// " + str(NFRAMES) + " frames x " + str(NSPEC) + " f32 coefficients of LCG noise,\n"
        "/// and the per-band `can_pns` / `pns_ener` the reference marks for them.\n"
        "/// The psy bands feeding mark_pns are recomputed in the test from the same\n"
        "/// spectra (the psy port is bit-exact, §277), so they are not duplicated here.\n"
    )

    body = []
    body.append(header)
    body.append("")
    body.append("///|")
    body.append("pub let aac_pns_spec : Array[Array[Double]] = [")
    body.append(fmt_array(specs, fmt_double))
    body.append("]")
    body.append("")
    body.append("///|")
    body.append("pub let aac_pns_ref_can : Array[Array[Int]] = [")
    body.append(fmt_array(cans, lambda v: str(int(v))))
    body.append("]")
    body.append("")
    body.append("///|")
    body.append("pub let aac_pns_ref_ener : Array[Array[Double]] = [")
    body.append(fmt_array(eners, fmt_double))
    body.append("]")
    body.append("")
    for name, rows, typ in (
        ("aac_pns_ref_sf", sfs, "Int"),
        ("aac_pns_ref_cb", cbs, "Int"),
        ("aac_pns_ref_zero", zeros, "Int"),
        ("aac_pns_ref_final_bt", final_bt, "Int"),
        ("aac_pns_ref_final_sf", final_sf, "Int"),
        ("aac_pns_ref_final_zero", final_zero, "Int"),
    ):
        body.append("///|")
        body.append("pub let %s : Array[Array[%s]] = [" % (name, typ))
        body.append(fmt_array(rows, lambda v: str(int(v))))
        body.append("]")
        body.append("")
    body.append("///|")
    body.append("pub let aac_pns_ref_final_ener : Array[Array[Double]] = [")
    body.append(fmt_array(final_ener, fmt_double))
    body.append("]")
    body.append("")

    with open(os.path.join(OUT_DIR, "fixtures.mbt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body))

    pkg = (
        'import {\n  "ffmpeg/moonbit/libavcodec",\n} for "test"\n'
    )
    with open(os.path.join(OUT_DIR, "moon.pkg"), "w", encoding="utf-8", newline="\n") as f:
        f.write(pkg)
    print("wrote %s/fixtures.mbt (%d frames)" % (OUT_DIR, len(specs)))


main()
