"""Generate the `aac_pns_vectors` fixture from the C `mark_pns` reference.

Runs `_ref/aacenc/aac_ref.exe --pns` (FFmpeg 9.0.2 `aaccoder.c` `mark_pns` on an
LCG-noise spectrum) and writes the MoonBit fixture package consumed by
`libavcodec/aac_pns_vectors/`.

    bash _ref/aacenc/build.sh
    python scripts/gen_aac_pns_vectors.py

The noise spectrum is needed because PNS only fires on noise-like bands (the psy
model must report `spread >= spread_threshold`, 0.75 at lambda 120); the tonal
synthetic spectrum of the default harness mode never gets there.
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
REF = os.path.join(REPO, "_ref", "aacenc", "aac_ref.exe")
OUT_DIR = os.path.join(REPO, "libavcodec", "aac_pns_vectors")
NFRAMES = 5
NSPEC = 1024
NBANDS = 49


def run():
    res = subprocess.run(
        [REF, "--pns"], capture_output=True, text=True, cwd=os.path.dirname(REF)
    )
    if res.returncode != 0:
        sys.exit("reference failed: " + res.stderr[-2000:])
    return res.stdout.splitlines()


def parse(lines):
    specs, cans, eners = [], [], []
    cur_spec = None
    cur_can = None
    cur_ener = None
    for line in lines:
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "SPEC":
            cur_spec = [float(v) for v in parts[2:]]
            if len(cur_spec) != NSPEC:
                sys.exit("short SPEC: %d" % len(cur_spec))
        elif parts[0] == "PSNMARK":
            if cur_can is None:
                cur_can, cur_ener = [], []
            cur_can.append(int(parts[2]))
            cur_ener.append(float(parts[3]))
        elif parts[0] == "END":
            if cur_spec is None or cur_can is None:
                sys.exit("incomplete frame")
            specs.append(cur_spec)
            cans.append(cur_can)
            eners.append(cur_ener)
            cur_spec = cur_can = cur_ener = None
    if len(specs) != NFRAMES:
        sys.exit("expected %d frames, got %d" % (NFRAMES, len(specs)))
    for c in cans:
        if len(c) != NBANDS:
            sys.exit("expected %d bands, got %d" % (NBANDS, len(c)))
    return specs, cans, eners


def fmt_double(v):
    return repr(float(v))


def fmt_array(rows, conv):
    out = []
    for row in rows:
        out.append("  [" + ", ".join(conv(v) for v in row) + "],")
    return "\n".join(out)


def main():
    lines = run()
    specs, cans, eners = parse(lines)
    os.makedirs(OUT_DIR, exist_ok=True)

    header = (
        "///|\n"
        "/// AUTOGENERATED by scripts/gen_aac_pns_vectors.py from\n"
        "/// `_ref/aacenc/aac_ref.exe --pns` (FFmpeg 9.0.2 `aaccoder.c` `mark_pns`).\n"
        "/// Do not edit by hand. Regenerate with:\n"
        "///   bash _ref/aacenc/build.sh\n"
        "///   python scripts/gen_aac_pns_vectors.py\n"
        "///\n"
        "/// " + str(NFRAMES) + " frames x " + str(NSPEC) + " f32 coefficients of LCG noise,\n"
        "/// and the per-band `can_pns` / `pns_ener` the reference marks for them.\n"
        "/// The psy bands feeding mark_pns are recomputed in the test from the same\n"
        "/// spectra (the psy port is bit-exact, §277), so they are not duplicated here.\n"
    )

    body = []
    body.append(header)
    body.append("")
    body.append("///|")
    body.append("pub let aac_pns_spec : Array[Array[Double]] = [")
    body.append(fmt_array(specs, fmt_double))
    body.append("]")
    body.append("")
    body.append("///|")
    body.append("pub let aac_pns_ref_can : Array[Array[Int]] = [")
    body.append(fmt_array(cans, lambda v: str(int(v))))
    body.append("]")
    body.append("")
    body.append("///|")
    body.append("pub let aac_pns_ref_ener : Array[Array[Double]] = [")
    body.append(fmt_array(eners, fmt_double))
    body.append("]")
    body.append("")

    with open(os.path.join(OUT_DIR, "fixtures.mbt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(body))

    pkg = (
        'import {\n  "ffmpeg/moonbit/libavcodec",\n} for "test"\n'
    )
    with open(os.path.join(OUT_DIR, "moon.pkg"), "w", encoding="utf-8", newline="\n") as f:
        f.write(pkg)
    print("wrote %s/fixtures.mbt (%d frames)" % (OUT_DIR, len(specs)))


main()
