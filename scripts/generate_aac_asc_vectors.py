"""MP4 AAC-LC ASC/PCE-only bootstrap references from FFmpeg 9.0.2.

All reference PCM decodes the MP4 with skip_manual, preserving encoded
frames/priming so the raw packet decoder can compare every sample.
ffprobe supplies ASC bytes, packet offsets/sizes and channel metadata.
"""
import base64
import json
from pathlib import Path
import subprocess
import textwrap

ROOT = Path(__file__).resolve().parents[1]
IMAGE = "linuxserver/ffmpeg:9.0.2"


def run(args, data=None, probe=False):
    command = ["docker", "run", "--rm", "-i"]
    if probe:
        command += ["--entrypoint", "ffprobe"]
    result = subprocess.run(command + [IMAGE, "-v", "error", *args], input=data,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
    if result.returncode:
        raise RuntimeError(result.stderr.decode("utf-8", errors="replace"))
    return result.stdout


def emit(name, data):
    chunks = textwrap.wrap(base64.b64encode(data).decode("ascii"), 112)
    return "///|\nlet " + name + " : Bytes = " + " +\n  ".join('b"' + c + '"' for c in chunks) + "\n"


def dump_bytes(dump):
    return b"".join(bytes.fromhex(line.split(":", 1)[1].strip().split("  ", 1)[0])
                    for line in dump.strip().splitlines())


def first_audio_element(packet):
    # Skip the encoder's optional leading FIL element; PCE must reside
    # only in ASC for these fixtures, not supply the decoder's layout.
    bits = "".join(f"{byte:08b}" for byte in packet)
    pos = 0
    while True:
        kind = int(bits[pos:pos + 3], 2)
        pos += 3
        if kind != 6:
            return kind
        count = int(bits[pos:pos + 4], 2)
        pos += 4
        if count == 15:
            count += int(bits[pos:pos + 8], 2) - 1
            pos += 8
        pos += count * 8


lines = ["///|\n/// MP4 AAC-LC references generated by scripts/generate_aac_asc_vectors.py.",
         "/// Docker linuxserver/ffmpeg:9.0.2; ASC/packet metadata from ffprobe.",
         "/// PCE layouts occur in ASC only. PCM is interleaved s16le with",
         "/// -flags2 +skip_manual, preserving priming and complete encoded frames.",
         "/// LGPL-2.1-or-later.\n"]
for name, layout, channels, flags in [
    ("stereo", "stereo", 2, []),
    ("pce51", "5.1", 6, ["-aac_pce", "1"]),
    ("pce71", "7.1", 8, ["-aac_pce", "1"]),
]:
    frequencies = [330, 440, 550, 80, 660, 770, 880, 990][:channels]
    expr = "|".join(f"0.08*sin(2*PI*{freq}*t)" for freq in frequencies)
    signal = f"aevalsrc='{expr}':s=48000:d=0.05:c={layout}"
    movie = run(["-f", "lavfi", "-i", signal, "-c:a", "aac", "-b:a", "192k", *flags,
                 "-movflags", "frag_keyframe+empty_moov+default_base_moof", "-f", "mp4", "pipe:1"])
    probe = json.loads(run(["-show_streams", "-show_packets", "-show_data", "-of", "json", "pipe:0"], movie, probe=True))
    stream = probe["streams"][0]
    assert stream["channels"] == channels
    asc = dump_bytes(stream["extradata"])
    packets = probe["packets"]
    for packet in packets:
        raw = movie[int(packet["pos"]):int(packet["pos"]) + int(packet["size"])]
        assert raw == dump_bytes(packet["data"])
        assert first_audio_element(raw) in (0, 1)
    pcm = run(["-flags2", "+skip_manual", "-i", "pipe:0", "-f", "s16le", "pipe:1"], movie)
    assert len(pcm) == len(packets) * 1024 * channels * 2, (name, len(pcm), len(packets))
    prefix = "aac_asc_" + name
    lines.append(f"/// {name}: {channels} channels, {len(packets)} packets; ASC {asc.hex()}.\n")
    lines.append(emit(prefix + "_mp4_b64", movie))
    lines.append(emit(prefix + "_config_b64", asc))
    lines.append(emit(prefix + "_pcm_b64", pcm))
    lines.append(f"///|\nlet {prefix}_packets : Array[(Int64, UInt32)] = [")
    lines += [f'  ({packet["pos"]}, {packet["size"]}),' for packet in packets]
    lines.append("]\n")
    print(name, "MP4", len(movie), "ASC", asc.hex(), "packets", len(packets), "samples", len(pcm) // 2)

(ROOT / "libavformat/aac_asc_realdata_wbtest.mbt").write_text("\n".join(lines), encoding="utf-8", newline="\n")
