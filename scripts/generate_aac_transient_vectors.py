"""Generate mono AAC window-switching vectors with FFmpeg 9.0.2.

Requires the local linuxserver/ffmpeg:9.0.2 Docker image. Reference PCM
comes from decoding the encoded stream, never from the source waveform.
"""

import base64
from pathlib import Path
import subprocess
import textwrap
import re

IMAGE = "linuxserver/ffmpeg:9.0.2"
SIGNAL = (
    "aevalsrc='0.04*sin(2*PI*440*t)+"
    "if(lt(mod(t+0.021,0.06),0.003),"
    "0.6*sin(2*PI*3300*t)+0.2*sin(2*PI*7100*t),0)':s=48000:d=0.25"
)


def ffmpeg(args, data=None):
    result = subprocess.run(
        ["docker", "run", "--rm", "-i", IMAGE, "-v", "error", *args],
        input=data, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        timeout=60,
    )
    if result.returncode:
        raise RuntimeError(result.stderr.decode("utf-8", errors="replace"))
    return result.stdout


def emit(name, data):
    chunks = textwrap.wrap(base64.b64encode(data).decode("ascii"), 112)
    return "///|\nlet " + name + " : Bytes = " + " +\n  ".join(
        'b"' + chunk + '"' for chunk in chunks
    ) + "\n"


lines = [
    "///|\n/// Real mono AAC-LC transient vectors; generated by",
    "/// scripts/generate_aac_transient_vectors.py using Docker",
    "/// linuxserver/ffmpeg:9.0.2. The script records the source expression,",
    "/// encoder flags and reference decode command. LGPL-2.1-or-later.\n",
]
for name, encoder, flags in [
    ("native", "aac", ["-aac_tns", "1", "-aac_pns", "1"]),
    ("fdk", "libfdk_aac", []),
]:
    encoded = ffmpeg([
        "-f", "lavfi", "-i", SIGNAL, "-ac", "1", "-c:a", encoder,
        "-profile:a", "aac_low", "-b:a", "64k", *flags, "-f", "adts", "pipe:1",
    ])
    pcm = ffmpeg(["-i", "pipe:0", "-c:a", "pcm_s16le", "-f", "s16le", "pipe:1"], encoded)
    lines.append(f"/// {encoder}: {len(encoded)} ADTS bytes, {len(pcm) // 2} reference samples.\n")
    lines.append(emit(f"aac_transient_{name}_b64", encoded))
    lines.append(emit(f"aac_transient_{name}_pcm_b64", pcm))
    print(name, "ADTS bytes", len(encoded), "PCM samples", len(pcm) // 2)

# Pulse has no encoder option in these encoders. Build its syntax using
# aactab.c Huffman words; obtain all expected PCM from FFmpeg decoding it.
source = (Path(__file__).resolve().parents[2] / "libavcodec/aactab.c").read_text(encoding="utf-8")


def table(name):
    body = re.search(r"\b" + name + r"\s*\[[^]]*\]\s*=\s*\{([^}]+)\}", source).group(1)
    return [int(token.strip(), 0) for token in body.split(",") if token.strip()]


sf_codes, sf_bits = table("ff_aac_scalefactor_code"), table("ff_aac_scalefactor_bits")
codes, bits = table("codes5"), table("bits5")


def pulse_frame(pulses, second_book=5, start=0):
    encoded_bits = []

    def put(value, size):
        encoded_bits.extend((value >> i) & 1 for i in reversed(range(size)))

    put(0, 3)  # SCE
    put(0, 4)  # instance tag
    put(180, 8)  # global_gain
    put(0, 1)  # ICS reserved
    put(0, 2)  # ONLY_LONG
    put(1, 1)  # KBD
    put(2, 6)  # max_sfb
    put(0, 1)  # no predictor
    for book in (5, second_book):
        put(book, 4)
        put(1, 5)  # one band per section
    put(sf_codes[60], sf_bits[60])  # first SF unchanged
    if second_book == 5:
        put(sf_codes[64], sf_bits[64])  # next SF +4 (different pulse scale)
    elif second_book == 13:
        put(256, 9)  # first PNS band, NOISE_PRE
    put(bool(pulses), 1)
    if pulses:
        put(len(pulses) - 1, 2)
        put(start, 6)
        for offset, amp in pulses:
            put(offset, 5)
            put(amp, 4)
    put(0, 1)  # TNS absent
    put(0, 1)  # gain control absent
    for book, values in [(5, [0, 1, -2, 3]), (second_book, [-1, 0, 2, -3])]:
        if book == 5:
            for first, second in zip(values[::2], values[1::2]):
                row = (first + 4) * 9 + second + 4
                put(codes[row], bits[row])
    put(7, 3)  # END and zero byte padding
    while len(encoded_bits) % 8:
        put(0, 1)
    payload = bytes(sum(encoded_bits[i + j] << (7 - j) for j in range(8))
                    for i in range(0, len(encoded_bits), 8))
    size = len(payload) + 7
    return bytes([0xff, 0xf1, 0x4c, 0x40 | (size >> 11), (size >> 3) & 255,
                  ((size & 7) << 5) | 0x1f, 0xfc]) + payload


pulse = b"".join([
    pulse_frame([(0, 3)]),  # a zero coefficient becomes nonzero
    pulse_frame([(0, 15), (1, 2), (1, 5), (1, 1)]),  # all four, both signs
    pulse_frame([(3, 2), (1, 3), (0, 1), (3, 15)]),  # band boundary and duplicate position
    pulse_frame([(0, 15)], second_book=0, start=1),  # ZERO_BT ignored
    pulse_frame([(0, 15)], second_book=13, start=1),  # NOISE_BT ignored
    pulse_frame([]),
])
pulse_pcm = ffmpeg(["-i", "pipe:0", "-f", "s16le", "pipe:1"], pulse)
lines.append("/// Synthetic pulse syntax (six frames); reference decoded by FFmpeg 9.0.2.\n")
lines.append(emit("aac_pulse_b64", pulse))
lines.append(emit("aac_pulse_pcm_b64", pulse_pcm))
print("pulse ADTS bytes", len(pulse), "PCM samples", len(pulse_pcm) // 2)

output = Path(__file__).resolve().parents[1] / "libavcodec/aac_transient_realdata_wbtest.mbt"
output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
