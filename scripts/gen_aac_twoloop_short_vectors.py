"""Generate MoonBit fixtures for the eight-short-window twoloop search.

The C harness (_ref/aacenc/aac_ref.exe --short) analyses a 1024-line spectrum as
eight 128-sample windows and then runs `search_for_quantizers_twoloop` over the
resulting `psy_bands[w*16+g]` slots, walking window groups with
`w += group_len[w]`.  The grouping patterns are the first five bytes of
`window_grouping[]` (`aacpsy.c:398`), i.e. what FFmpeg's block switcher can
actually emit, so groups of 1, 2 and 3 windows all appear.

Usage:
    bash _ref/aacenc/build.sh
    ./_ref/aacenc/aac_ref.exe --short > _ref/aacenc/vectors_short.txt
    python scripts/gen_aac_twoloop_short_vectors.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_ref", "aacenc", "vectors_short.txt")
DST = os.path.join(
    ROOT, "libavcodec", "aac_twoloop_vectors", "fixtures_short.mbt"
)

HEADER = """///|
/// AUTOGENERATED by scripts/gen_aac_twoloop_short_vectors.py from
/// _ref/aacenc/vectors_short.txt (FFmpeg 9.0.2 aaccoder_twoloop.h run on eight
/// short windows).  Do not edit by hand.  Regenerate with:
///   bash _ref/aacenc/build.sh
///   ./aac_ref.exe --short > vectors_short.txt
///   python scripts/gen_aac_twoloop_short_vectors.py
///
/// {frames} frames, each analysed as 8 windows x {bands} scalefactor bands with
/// the window grouping of `SHORTGRP` (the `window_grouping[]` byte of frame i
/// expanded the way `psy_3gpp_window` does it).  Only the slots a window
/// *group* start owns carry a decision - `w * 16 + g` for the group's first
/// window - and `aac_two_short_slot[f]` names them, so the port's slot layout
/// is compared against C's instead of assumed.
"""


def parse():
    frames = []
    cur = None
    nb = 0
    with open(SRC, "r", encoding="ascii") as fh:
        for raw in fh:
            parts = raw.split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "FRAME":
                cur = {
                    "spec": [], "alloc": "0", "prev": "0", "group": [],
                    "slot": [], "sf": [], "cb": [], "zeroes": [], "maxval": [],
                }
            elif tag == "SPEC":
                cur["spec"] = parts[2:]
            elif tag == "PSYALLOC":
                cur["alloc"] = parts[1]
            elif tag == "SHORTCFG":
                nb = int(parts[2])
            elif tag == "SHORTGRP":
                cur["group"] = parts[1:9]
                # frame index is tracked by the caller below
                cur["prev"] = str(len(frames) % 2)
            elif tag == "TWOBAND":
                cur["slot"].append(parts[1])
                cur["sf"].append(parts[2])
                cur["cb"].append(parts[3])
                cur["zeroes"].append(parts[4])
                cur["maxval"].append(parts[5])
            elif tag == "END":
                frames.append(cur)
                cur = None
    if not frames or nb == 0:
        raise SystemExit("no frames parsed from %s" % SRC)
    return frames, nb


def emit_matrix(name, cast, rows, per_line):
    out = ["///|", "pub let %s : Array[Array[%s]] = [" % (name, cast)]
    for row in rows:
        out.append("  [")
        for i in range(0, len(row), per_line):
            out.append("    %s," % ", ".join(row[i:i + per_line]))
        out.append("  ],")
    out.append("]")
    out.append("")
    return out


def emit_vector(name, cast, values, per_line):
    out = ["///|", "pub let %s : Array[%s] = [" % (name, cast)]
    for i in range(0, len(values), per_line):
        out.append("  %s," % ", ".join(values[i:i + per_line]))
    out.append("]")
    out.append("")
    return out


def main():
    frames, nb = parse()
    lines = [HEADER.format(frames=len(frames), bands=nb)]
    lines += emit_matrix("aac_two_short_spec", "Double",
                         [f["spec"] for f in frames], 6)
    lines += emit_vector("aac_two_short_prev", "Int32",
                         [f["prev"] for f in frames], 8)
    lines += emit_vector("aac_two_short_alloc", "Int32",
                         [f["alloc"] for f in frames], 8)
    lines += emit_matrix("aac_two_short_group_len", "Int32",
                         [f["group"] for f in frames], 8)
    for key, name, cast, per_line in (
        ("slot", "aac_two_short_slot", "Int32", 14),
        ("sf", "aac_two_short_sf", "Int32", 14),
        ("cb", "aac_two_short_cb", "Int32", 14),
        ("zeroes", "aac_two_short_zeroes", "Int32", 14),
        ("maxval", "aac_two_short_maxvals", "Double", 4),
    ):
        lines += emit_matrix(name, cast, [f[key] for f in frames], per_line)

    body = "\n".join(lines)
    assert len(body) > 4000, "generated fixture is suspiciously short"
    tmp = DST + ".new"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    os.replace(tmp, DST)
    print("wrote %s (%d bytes, %d frames, %d band decisions)" % (
        DST, len(body), len(frames), sum(len(f["slot"]) for f in frames)))


main()
