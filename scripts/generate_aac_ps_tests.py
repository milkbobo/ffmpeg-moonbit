# -*- coding: utf-8 -*-
"""Emit the Parametric Stereo white-box tests from `_build/ps_work` artifacts.

Outputs (both regenerated wholesale):
  libavcodec/aac_ps_syntax_wbtest.mbt  the C-dumped PS payload bitstrings of
      the two HE-AACv2 streams, replayed through `read_data` with every
      post-parse state line compared bit-exactly
  libavcodec/aac_ps_pcm_wbtest.mbt     end-to-end PCM of the same streams
      against the docker FFmpeg 9.0.2 native-decoder s16le output, with the
      SBR slice's max-diff tolerance style

Run after `_build/ps_work/run_trace.sh`.
"""
import base64
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORK = ROOT / "_build" / "ps_work"

HDR = """///|
/// Generated by scripts/generate_aac_ps_tests.py — do not edit by hand.
/// Vectors: docker linuxserver/ffmpeg:9.0.2 libfdk_aac -profile:a aac_he_v2;
/// references from the same build's native float AAC decoder and the
/// instrumented-C dumps of `_build/ps_work`. LGPL-2.1-or-later.
"""


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode()


def bytes_lit(b64s: str, chunk_size: int = 8192) -> str:
    parts = []
    for i in range(0, len(b64s), chunk_size):
        parts.append('b"%s"' % b64s[i:i + chunk_size])
    return " +\n  ".join(parts)


def adts_trim(data: bytes, nframes: int) -> bytes:
    """First `nframes` ADTS frames."""
    out = b""
    pos = 0
    for _ in range(nframes):
        if pos + 7 > len(data):
            raise SystemExit("adts_trim: truncated")
        hdr = data[pos:pos + 7]
        flen = ((hdr[3] & 0x03) << 11) | (hdr[4] << 3) | (hdr[5] >> 5)
        out += data[pos:pos + flen]
        pos += flen
    return out


def read_payloads(name):
    pay = (WORK / "dumps" / (name + "_payloads.txt")).read_text().splitlines()
    lines = (WORK / "dumps" / (name + "_syntax.txt")).read_text().splitlines()
    assert len(pay) == len(lines), (name, len(pay), len(lines))
    bits_list = []
    keep_lines = []
    for ln, st in zip(pay, lines):
        parts = ln.split()
        left = int(parts[2].split("=")[1])
        bits = parts[3]
        assert len(bits) == left
        # avformat_find_stream_info's probe decode re-decodes the first
        # frames with a fresh decoder instance (num_env_old back at 0), so
        # the dump starts with duplicated payloads whose state lines a
        # sequential replay cannot reproduce. Keep the first parse (it
        # leaves the state the C carried into the next payload) and skip
        # the duplicate, within the first six payloads only.
        if len(bits_list) < 6 and bits_list and bits_list[-1] == bits:
            continue
        bits_list.append(bits)
        # Renumber the dumped id: after collapsing probe duplicates the
        # original call counter no longer matches the replay sequence.
        keep_lines.append("PS %d %s" % (len(keep_lines) + 1, st.split(" ", 2)[2]))
    return bits_list, keep_lines


def gen_syntax(streams):
    out = [HDR]
    for name in streams:
        bits_list, lines = read_payloads(name)
        out.append("///| `%s.aac`: PS payload bitstrings as the instrumented C" % name)
        out.append("/// saw them (one entry per `ff_ps_read_data` call).")
        out.append("let %s_payloads : Array[String] = [" % name)
        for bits in bits_list:
            out.append('  "%s",' % bits)
        out.append("]")
        out.append("")
        out.append("///| Matching post-parse state lines (`ps_dump_syntax`).")
        out.append("let %s_syntax : Array[String] = [" % name)
        for ln in lines:
            out.append('  "%s",' % ln.replace("\\", "\\\\").replace('"', '\\"'))
        out.append("]")
        out.append("")
    out.append(SYNTAX_DRIVER)
    (ROOT / "libavcodec" / "aac_ps_syntax_wbtest.mbt").write_text(
        "\n".join(out) + "\n", encoding="utf-8", newline="\n")


SYNTAX_DRIVER = r"""///| Replay the C-dumped payload bitstrings through `read_data` and compare
/// every post-parse state line bit-exactly. A dedicated `AacPs` carries the
/// cross-payload state (dt coding references the previous envelope).
fn ps_syntax_run(
  payloads : Array[String],
  expected : Array[String],
  tag : String,
) -> String {
  let ps = aac_ps_new()
  aac_ps_syntax_trace.val = []
  aac_ps_syntax_trace_on.val = true
  aac_ps_read_count.val = 0
  for i in 0..<payloads.length() {
    let bits = payloads[i]
    let nbytes = (bits.length() + 7) / 8
    let buf = Array::make(nbytes, (0).to_byte())
    for k in 0..<bits.length() {
      if bits[k] == '1' {
        buf[k / 8] = (buf[k / 8].to_int() | (1 << (7 - k % 8))).to_byte()
      }
    }
    let gb = BitReader::new(Bytes::from_array(buf))
    ignore(ps.common.read_data(gb, bits.length()))
  }
  aac_ps_syntax_trace_on.val = false
  let got = aac_ps_syntax_trace.val
  if got.length() != expected.length() {
    return "\{tag}: \{got.length()} trace lines vs \{expected.length()} expected"
  }
  for i in 0..<expected.length() {
    if got[i] != expected[i] {
      let a = got[i]
      let b = expected[i]
      let mut d = 0
      while d < a.length() && d < b.length() && a[d] == b[d] {
        d = d + 1
      }
      let lo = if d > 40 { d - 40 } else { 0 }
      return "\{tag} line \{i} diverges at \{d}:\n  want: ...\{b[lo:]}\n  got : ...\{a[lo:]}"
    }
  }
  ""
}

test "AAC PS syntax vs instrumented C (hev2_48_32k + hev2_44_24k)" {
  let m = ps_syntax_run(hev2_48_32k_payloads, hev2_48_32k_syntax, "48_32k")
  assert_eq(m, "")
  let m2 = ps_syntax_run(hev2_44_24k_payloads, hev2_44_24k_syntax, "44_24k")
  assert_eq(m2, "")
}"""


PCM_DRIVER = r"""fn ps_pcm_check(
  stream : Bytes,
  pcm : Bytes,
  tag : String,
) -> Unit raise {
  let header = ff_adts_header_parse_buf(stream).unwrap()
  let config = new_mpeg4_audio_config()
  config.object_type = 2
  config.sampling_index = header.sampling_index
  config.sample_rate = header.sample_rate
  config.chan_config = header.chan_config
  config.channels = header.chan_config
  config.frame_length = 1024
  config.sbr = -1
  config.ps = -1
  let dec = new_aac_decoder(config, 2)
  let mut pos = 0
  let mut frames = 0
  let mut max_diff = 0
  let mut exact = 0
  let mut samples = 0
  while pos < stream.length() {
    let hdr = ff_adts_header_parse_buf(
      stream
        .clamped_view(
          start=pos,
          end=pos + av_aac_adts_header_size,
        )
        .to_owned(),
    ).unwrap()
    let end = pos + hdr.frame_length
    let payload_start = pos +
      av_aac_adts_header_size +
      (if hdr.crc_absent == 0 { 2 } else { 0 })
    let payload = stream.clamped_view(start=payload_start, end~).to_owned()
    let out = dec.decode_frame(payload).unwrap()
    let nch = out.length()
    assert_eq(nch, 2)
    let n = out[0].samples.length()
    for ch in 0..<nch {
      assert_eq(out[ch].samples.length(), n)
    }
    for i in 0..<n {
      for ch in 0..<nch {
        let idx = (samples + i) * nch + ch
        assert_true(idx * 2 + 1 < pcm.length())
        let value = pcm[idx * 2].to_int() | (pcm[idx * 2 + 1].to_int() << 8)
        let want = if value >= 32768 { value - 65536 } else { value }
        let got = aac_s16p(out[ch].samples[i])
        let diff = if got > want { got - want } else { want - got }
        if diff > max_diff {
          max_diff = diff
        }
        if diff == 0 {
          exact = exact + 1
        }
      }
    }
    samples = samples + n
    frames = frames + 1
    pos = end
  }
  println(
    "\{tag}: frames=\{frames} samples=\{samples} max_diff=\{max_diff} exact=\{exact * 100 / (samples * 2)}%",
  )
  assert_true(max_diff <= ps_pcm_max_diff)
}

///| Tolerance vs the native f32 decoder at s16 scale.
let ps_pcm_max_diff : Int = 2

test "AAC PS end-to-end PCM vs native decoder (HE-AACv2)" {
  ps_pcm_check(
    @libavutil.av_base64_decode(hev2_48_32k_pcm_adts_b64, 1 << 16).unwrap(),
    @libavutil.av_base64_decode(hev2_48_32k_pcm_b64, 1 << 20).unwrap(),
    "48_32k",
  )
  ps_pcm_check(
    @libavutil.av_base64_decode(hev2_44_24k_pcm_adts_b64, 1 << 16).unwrap(),
    @libavutil.av_base64_decode(hev2_44_24k_pcm_b64, 1 << 20).unwrap(),
    "44_24k",
  )
}"""


def gen_pcm(streams):
    out = [HDR]
    for name in streams:
        data = (WORK / (name + ".aac")).read_bytes()
        pcm = (WORK / (name + ".pcm")).read_bytes()
        out.append("///| `%s.aac` + native-decoder s16le PCM (%d bytes)." % (
            name, len(pcm)))
        out.append("let %s_pcm_adts_b64 : Bytes = %s" % (name, bytes_lit(b64(data))))
        out.append("")
        out.append("let %s_pcm_b64 : Bytes = %s" % (name, bytes_lit(b64(pcm), 60000)))
        out.append("")
    out.append(PCM_DRIVER)
    (ROOT / "libavcodec" / "aac_ps_pcm_wbtest.mbt").write_text(
        "\n".join(out) + "\n", encoding="utf-8", newline="\n")


def main():
    streams = ["hev2_48_32k", "hev2_44_24k"]
    gen_syntax(streams)
    gen_pcm(streams)
    print("wrote aac_ps_syntax_wbtest.mbt, aac_ps_pcm_wbtest.mbt")


if __name__ == "__main__":
    main()
