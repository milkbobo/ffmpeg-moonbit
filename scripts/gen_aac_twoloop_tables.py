"""Generate libavcodec/aac_twoloop_tables.mbt from _ref/aacenc/tables.txt.

The C dumper (_ref/aacenc/dump_tables.c) prints every constant table the
twoloop quantizer indexes, in C's own index order.  Transcribing them by hand
is error prone (the 428-entry pow tables are f32 values that must round-trip
exactly), so they are generated instead.

Usage:
    cd _ref/aacenc && ./dump_tables.exe > tables.txt
    python scripts/gen_aac_twoloop_tables.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "_ref", "aacenc", "tables.txt")
DST = os.path.join(ROOT, "libavcodec", "aac_twoloop_tables.mbt")

# Entry counts per codebook, in ff_aac_codebook_vectors[] order (cb 1..11).
VEC_COUNTS = [81, 81, 81, 81, 81, 81, 64, 64, 169, 169, 289]
VEC_DIMS = [4, 4, 4, 4, 2, 2, 2, 2, 2, 2, 2]


def parse():
    tables = {}
    vecs = []
    bits = []
    with open(SRC, "r", encoding="ascii") as fh:
        for raw in fh:
            parts = raw.split()
            if not parts:
                continue
            tag = parts[0]
            if tag == "POW2SF":
                assert int(parts[1]) == 428
                tables["pow2sf"] = [float(x) for x in parts[2:]]
            elif tag == "POW34SF":
                assert int(parts[1]) == 428
                tables["pow34sf"] = [float(x) for x in parts[2:]]
            elif tag == "CBRANGE":
                assert int(parts[1]) == 12
                tables["cb_range"] = [int(x) for x in parts[2:]]
            elif tag == "CBMAXVAL":
                assert int(parts[1]) == 12
                tables["cb_maxval"] = [int(x) for x in parts[2:]]
            elif tag == "MAXVALCB":
                tables["maxval_cb"] = [int(x) for x in parts[2:]]
                assert len(tables["maxval_cb"]) == int(parts[1]) == 14
            elif tag == "VEC":
                k = int(parts[1])
                n = int(parts[2])
                assert k == len(vecs), (k, len(vecs))
                assert n == VEC_COUNTS[k] * VEC_DIMS[k], (k, n)
                vecs.append([float(x) for x in parts[3:]])
                assert len(vecs[-1]) == n
            elif tag == "BITS":
                k = int(parts[1])
                n = int(parts[2])
                assert k == len(bits), (k, len(bits))
                assert n == VEC_COUNTS[k], (k, n)
                bits.append([int(x) for x in parts[3:]])
                assert len(bits[-1]) == n
            elif tag == "CBRT":
                assert int(parts[1]) == 8192
                tables["cbrt_prod"] = [float(x) for x in parts[2:]]
                assert len(tables["cbrt_prod"]) == 8192
            else:
                raise SystemExit("unknown tag: " + tag)
    assert len(vecs) == 11 and len(bits) == 11
    tables["vecs"] = vecs
    tables["bits"] = bits
    return tables


def fmt_float(v):
    # repr() of a Python float parsed from %.9e round-trips the f32 exactly.
    return repr(v)


def wrap(values, conv, per_line, indent="  "):
    out = []
    line = indent
    for v in values:
        piece = conv(v) + ", "
        if len(line) + len(piece) > 88:
            out.append(line.rstrip())
            line = indent
        line += piece
    if line.strip():
        out.append(line.rstrip())
    return out


def emit_float_array(name, values, doc=None):
    out = []
    if doc:
        out += ["///|"] + ["/// " + d for d in doc]
    out.append("let {} : Array[Double] = [".format(name))
    out += wrap(values, fmt_float, 0)
    out.append("]")
    out.append("")
    return out


def emit_int_array(name, values, typ="Int32", doc=None):
    out = []
    if doc:
        out += ["///|"] + ["/// " + d for d in doc]
    out.append("let {} : Array[{}] = [".format(name, typ))
    out += wrap(values, str, 0)
    out.append("]")
    out.append("")
    return out


def main():
    t = parse()

    lines = [
        "///|",
        "/// AUTOGENERATED by scripts/gen_aac_twoloop_tables.py from",
        "/// _ref/aacenc/tables.txt (FFmpeg 9.0.2 aactab.c / aacenctab.h).",
        "/// Do not edit by hand. Regenerate with:",
        "///   cd _ref/aacenc && gcc -O1 -std=c11 -I. -ID:/project/FFmpeg-n9.0.2 \\",
        "///     -ID:/project/FFmpeg-n9.0.2/libavcodec -DHAVE_AV_CONFIG_H \\",
        "///     -c dump_tables.c -o dump_tables.o && gcc -o dump_tables.exe \\",
        "///     dump_tables.o aactab.o libavcodec_ref.a <libavutil> -lm ...",
        "///   ./dump_tables.exe > tables.txt",
        "///   python scripts/gen_aac_twoloop_tables.py",
        "///",
        "/// Every table keeps C's index order; the quantizer indexes them",
        "/// exactly as `aaccoder.c` does.  `pow2sf` / `pow34sf` are the f32",
        "/// values of `ff_aac_pow2sf_tab` / `ff_aac_pow34sf_tab` printed with",
        "/// %.9e (9 significant digits round-trip a binary32 exactly).",
        "/// Original FFmpeg code is LGPL-2.1-or-later.",
        "",
    ]

    lines += emit_float_array(
        "aac_twoloop_pow2sf",
        t["pow2sf"],
        ["`ff_aac_pow2sf_tab[428]`, `aactab.c:44` (f32)."],
    )
    lines += emit_float_array(
        "aac_twoloop_pow34sf",
        t["pow34sf"],
        ["`ff_aac_pow34sf_tab[428]`, `aactab.c:85` (f32)."],
    )
    lines += emit_int_array(
        "aac_twoloop_cb_range",
        t["cb_range"],
        doc=["`aac_cb_range[12]`, `aacenctab.h:138`."],
    )
    lines += emit_int_array(
        "aac_twoloop_cb_maxval",
        t["cb_maxval"],
        doc=["`aac_cb_maxval[12]`, `aacenctab.h:139`."],
    )
    lines += emit_int_array(
        "aac_twoloop_maxval_cb",
        t["maxval_cb"],
        doc=["`aac_maxval_cb[]`, `aacenctab.h:141`: quantised peak -> codebook."],
    )

    for k in range(11):
        lines += emit_float_array(
            "aac_twoloop_vec{}".format(k + 1),
            t["vecs"][k],
            [
                "`ff_aac_codebook_vectors[{}]` (codebook {}): {} vectors of"
                .format(k, k + 1, VEC_COUNTS[k]) + " dim {}.".format(VEC_DIMS[k]),
            ],
        )
    lines += ["///|", "/// The 11 codebook vector tables, indexed by `cb - 1`."]
    lines.append("let aac_twoloop_vectors : Array[Array[Double]] = [")
    for k in range(11):
        lines.append("  aac_twoloop_vec{},".format(k + 1))
    lines.append("]")
    lines.append("")

    for k in range(11):
        lines += emit_int_array(
            "aac_twoloop_bits{}".format(k + 1),
            t["bits"][k],
            doc=[
                "`ff_aac_spectral_bits[{}]` (codebook {}): {} entries."
                .format(k, k + 1, VEC_COUNTS[k]),
            ],
        )
    lines += ["///|", "/// The 11 spectral bit-count tables, indexed by `cb - 1`."]
    lines.append("let aac_twoloop_spectral_bits : Array[Array[Int32]] = [")
    for k in range(11):
        lines.append("  aac_twoloop_bits{},".format(k + 1))
    lines.append("]")
    lines.append("")

    lines += emit_float_array(
        "aac_twoloop_cbrt_prod",
        t["cbrt_prod"],
        [
            "`c*cbrtf(c)` for c in 0..8191, printed as f32 with %.9e.",
            "The escape branch of `quantize_and_encode_band_cost_ESC` computes",
            "that product with the single-precision `cbrtf`, which is *not*",
            "`float(c*cbrt((double)c))` - on this toolchain 2196 of the 8192",
            "values differ by one ulp - so the encoder's own values are",
            "transcribed here instead of being recomputed.",
        ],
    )

    # Sanity markers. Codebook 11 starts at (0, 0) and ends at the
    # escape/escape pair (64, 64) - `64.0f` is the BT_ESC sentinel that
    # aaccoder.c compares against, so a transcription slip there would be
    # silent until the cost function mis-discounts an escape.
    assert t["vecs"][10][0] == 0.0
    assert t["vecs"][10][-2] == 64.0 and t["vecs"][10][-1] == 64.0
    assert t["vecs"][0][:4] == [-1.0, -1.0, -1.0, -1.0]
    assert t["bits"][10][0] == 4

    with open(DST, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", DST)


if __name__ == "__main__":
    main()
