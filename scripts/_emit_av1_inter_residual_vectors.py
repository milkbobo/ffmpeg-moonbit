#!/usr/bin/env python3
"""Emit libavcodec/av1_inter_residual_vectors/residual_test.mbt from
%TEMP%/coeftree_dump.txt (dav1d 1.5.1 read_coef_tree + chroma loops with a
deterministic 1-bit coefficient reader)."""
import io
import os

TMP = os.environ.get('TEMP', r'C:\Users\milkb\AppData\Local\Temp')
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTDIR = os.path.join(ROOT, 'libavcodec', 'av1_inter_residual_vectors')
OUT = os.path.join(OUTDIR, 'residual_test.mbt')


def wrap(vals, per=16):
    return '\n'.join('    ' + ', '.join(vals[i:i + per]) + ','
                     for i in range(0, len(vals), per))


def main():
    rows = [l.split() for l in io.open(os.path.join(TMP, 'coeftree_dump.txt'))
            if l.strip()]
    assert len(rows) == 128, len(rows)
    cfg, rng, dif, leaves, hashes, ctx, maph = ([] for _ in range(7))
    for t in rows:
        assert t[0] == 'C' and len(t) == 211, len(t)
        cfg.extend(t[1:14])
        rng.append(t[14])
        dif.append('0x%sL' % t[15])
        leaves.append(t[16])
        hashes.append('0x%08xU' % int(t[17]))
        ctx.extend(t[18:210])
        maph.append('0x%08xU' % int(t[210]))
    os.makedirs(OUTDIR, exist_ok=True)
    pkg = os.path.join(OUTDIR, 'moon.pkg')
    if not os.path.exists(pkg):
        io.open(pkg, 'w', encoding='utf-8', newline='\n').write(
            'import {\n  "ffmpeg/moonbit/libavcodec",\n} for "test"\n')
    out = io.StringIO()
    w = out.write
    w('///|\n')
    w('/// Inter residual coefficient walk verified against dav1d 1.5.1\n')
    w('/// `read_coef_tree` plus the chroma `uvtx` loops over LCG byte streams.\n')
    w('/// The coefficient reader is a deterministic 1-bit stand-in so this\n')
    w('/// checks walk order, context updates and `txtp_map` only\n')
    w('/// (`scripts/_emit_av1_inter_residual_vectors.py`).\n\n')
    w('///|\n')
    w('fn av1_res_lcg_bytes(seed : UInt, n : Int) -> Bytes {\n')
    w('  let mut state = seed\n')
    w('  let out : Array[Byte] = []\n')
    w('  for _ in 0..<n {\n')
    w('    state = state * 1664525 + 1013904223\n')
    w('    out.push(((state >> 16) & 0xff).reinterpret_as_int().to_byte())\n')
    w('  }\n')
    w('  Bytes::from_array(out)\n')
    w('}\n\n')
    w('///|\n')
    w('fn av1_res_slice(src : Bytes, start : Int) -> Bytes {\n')
    w('  let out : Array[Byte] = []\n')
    w('  for i in start..<src.length() {\n')
    w('    out.push(src[i])\n')
    w('  }\n')
    w('  Bytes::from_array(out)\n')
    w('}\n\n')
    w('///|\n')
    w('test "inter residual walk matches dav1d" {\n')
    w('  let seeds : Array[UInt] = [0x31415926U, 0x27182818U]\n')
    for name, vals, ty in [
        ('cfg', cfg, 'Int'), ('exp_rng', rng, 'Int'),
        ('exp_dif', dif, 'Int64'), ('exp_leaves', leaves, 'Int'),
        ('exp_hash', hashes, 'UInt'), ('exp_ctx', ctx, 'Int'),
        ('exp_maphash', maph, 'UInt'),
    ]:
        w('  let %s : Array[%s] = [\n' % (name, ty))
        w(wrap(vals))
        w('\n  ]\n')
    w('  for s in 0..<2 {\n')
    w('    let stream = av1_res_lcg_bytes(seeds[s], 8192)\n')
    w('    for i in 0..<64 {\n')
    w('      let k = s * 64 + i\n')
    w('      let bs = cfg[k * 13]\n')
    w('      let bd0 = cfg[k * 13 + 1]\n')
    w('      let bd1 = cfg[k * 13 + 2]\n')
    w('      let abx = cfg[k * 13 + 3]\n')
    w('      let aby = cfg[k * 13 + 4]\n')
    w('      let bw = cfg[k * 13 + 5]\n')
    w('      let bh = cfg[k * 13 + 6]\n')
    w('      let a_lcoef : FixedArray[Int32] = FixedArray::make(32, 0)\n')
    w('      let l_lcoef : FixedArray[Int32] = FixedArray::make(32, 0)\n')
    w('      let a_ccoef : FixedArray[Int32] = FixedArray::make(64, 0)\n')
    w('      let l_ccoef : FixedArray[Int32] = FixedArray::make(64, 0)\n')
    w('      let txtp_map : FixedArray[Byte] = FixedArray::make(1024, 0)\n')
    w('      for j in 0..<32 {\n')
    w('        a_lcoef[j] = (j * 5 + bs) & 0x7f\n')
    w('        l_lcoef[j] = (j * 11 + (i % 8)) & 0x7f\n')
    w('      }\n')
    w('      for j in 0..<64 {\n')
    w('        a_ccoef[j] = (j * 3 + abx) & 0x7f\n')
    w('        l_ccoef[j] = (j * 7 + aby) & 0x7f\n')
    w('      }\n')
    w('      for j in 0..<1024 {\n')
    w('        txtp_map[j] = ((j * 7 + bs) & 0x0f).to_byte()\n')
    w('      }\n')
    w('      let msac = @libavcodec.Av1Msac::init(av1_res_slice(stream, i * 19), false)\n')
    w('      let reader : @libavcodec.Av1CoefReader = {\n')
    w('        decode: (_, _, _, _, tx, _, _, _) => {\n')
    w('          let bit = msac.decode_bool_equi().reinterpret_as_int()\n')
    w('          (bit, (tx + bit) & 15, 0x40 | bit)\n')
    w('        },\n')
    w('      }\n')
    w('      let leaves = Ref(0)\n')
    w('      let hash = Ref(0U)\n')
    w('      let record = (rx : Int, ry : Int, tx : Int, txtp : Int, eob : Int) => {\n')
    w('        leaves.val = leaves.val + 1\n')
    w('        hash.val = hash.val * 31U + (rx & 0x3f).reinterpret_as_uint()\n')
    w('        hash.val = hash.val * 31U + (ry & 0x3f).reinterpret_as_uint()\n')
    w('        hash.val = hash.val * 31U + tx.reinterpret_as_uint()\n')
    w('        hash.val = hash.val * 31U + txtp.reinterpret_as_uint()\n')
    w('        hash.val = hash.val * 31U + eob.reinterpret_as_uint()\n')
    w('      }\n')
    w('      let w4 = if bd0 < bw - abx { bd0 } else { bw - abx }\n')
    w('      let h4 = if bd1 < bh - aby { bd1 } else { bh - aby }\n')
    w('      let cw4 = (w4 + cfg[k * 13 + 11]) >> cfg[k * 13 + 11]\n')
    w('      let ch4 = (h4 + cfg[k * 13 + 12]) >> cfg[k * 13 + 12]\n')
    w('      @libavcodec.av1_read_inter_residual(\n')
    w('        reader, bs, cfg[k * 13 + 7], cfg[k * 13 + 8].reinterpret_as_uint(),\n')
    w('        cfg[k * 13 + 9].reinterpret_as_uint(), cfg[k * 13 + 10], w4, h4, cw4,\n')
    w('        ch4, cfg[k * 13 + 11], cfg[k * 13 + 12], true, abx, aby, bw, bh,\n')
    w('        a_lcoef, l_lcoef, a_ccoef, l_ccoef, txtp_map,\n')
    w('        Some((rx, ry, tx, txtp, eob) => record(rx, ry, tx, txtp, eob)),\n')
    w('        Some((_, cx, cy, tx, txtp, eob) => record(cx, cy, tx, txtp, eob)),\n')
    w('      )\n')
    w('      if leaves.val != exp_leaves[k] || hash.val != exp_hash[k] {\n')
    w('        fail("residual k " + k.to_string() + " leaves/hash " + leaves.val.to_string() + "/" + hash.val.to_string() + " != " + exp_leaves[k].to_string() + "/" + exp_hash[k].to_string())\n')
    w('      }\n')
    w('      assert_eq(msac.rng.reinterpret_as_int(), exp_rng[k])\n')
    w('      assert_eq((msac.dif >> 32).reinterpret_as_int64(), exp_dif[k])\n')
    w('      let mut maphash = 0U\n')
    w('      for r in 0..<bd1 {\n')
    w('        for c in 0..<bd0 {\n')
    w('          maphash = maphash * 31U +\n')
    w('            (txtp_map[((aby & 31) + r) * 32 + (abx & 31) + c].to_int() & 0x0f).reinterpret_as_uint()\n')
    w('        }\n')
    w('      }\n')
    w('      if maphash != exp_maphash[k] {\n')
    w('        fail("residual k " + k.to_string() + " maphash " + maphash.to_string() + " != " + exp_maphash[k].to_string())\n')
    w('      }\n')
    w('      for j in 0..<32 {\n')
    w('        if a_lcoef[j] != exp_ctx[k * 192 + j] || l_lcoef[j] != exp_ctx[k * 192 + 32 + j] {\n')
    w('          fail("residual lcoef k " + k.to_string() + " j " + j.to_string())\n')
    w('        }\n')
    w('      }\n')
    w('      for j in 0..<64 {\n')
    w('        if a_ccoef[j] != exp_ctx[k * 192 + 64 + j] || l_ccoef[j] != exp_ctx[k * 192 + 128 + j] {\n')
    w('          fail("residual ccoef k " + k.to_string() + " j " + j.to_string())\n')
    w('        }\n')
    w('      }\n')
    w('    }\n')
    w('  }\n')
    w('}\n')
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(out.getvalue())
    print('wrote', OUT, len(out.getvalue()), 'bytes')


if __name__ == '__main__':
    main()
