"""Generate indexed/PCE multichannel AAC references using FFmpeg 9.0.2.

The reference PCM always decodes the same encoded bytes. Real 5.1/7.1
signals have distinct frequencies per speaker. Synthetic PCE streams
change element arrival order to expose overlap-history channel swaps.
"""
import base64
from pathlib import Path
import re
import subprocess
import textwrap

ROOT = Path(__file__).resolve().parents[1]
IMAGE = "linuxserver/ffmpeg:9.0.2"


def ffmpeg(args, data=None):
    result = subprocess.run(["docker", "run", "--rm", "-i", IMAGE, "-v", "error", *args],
                            input=data, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60)
    if result.returncode:
        raise RuntimeError(result.stderr.decode("utf-8", errors="replace"))
    return result.stdout


def emit(name, data):
    chunks = textwrap.wrap(base64.b64encode(data).decode("ascii"), 112)
    return "///|\nlet " + name + " : Bytes = " + " +\n  ".join('b"' + c + '"' for c in chunks) + "\n"


lines = ["///|\n/// AAC channel-layout vectors generated by scripts/generate_aac_layout_vectors.py.",
         "/// Docker linuxserver/ffmpeg:9.0.2; reference PCM is interleaved s16le.",
         "/// Source expressions, encoder options and synthetic syntax are in the script.",
         "/// LGPL-2.1-or-later.\n"]


def vector(name, encoded, channels):
    pcm = ffmpeg(["-i", "pipe:0", "-f", "s16le", "pipe:1"], encoded)
    config = ((encoded[2] & 1) << 2) | (encoded[3] >> 6)
    frames = len(pcm) // (2048 * channels)
    lines.append(f"/// {name}: channel_config={config}, {channels} channels, {frames} frames.\n")
    lines.append(emit("aac_layout_" + name + "_b64", encoded))
    lines.append(emit("aac_layout_" + name + "_pcm_b64", pcm))
    print(name, "config", config, "channels", channels, "frames", frames, "ADTS bytes", len(encoded))


for name, layout, channels, flags in [
    ("native51", "5.1", 6, []),
    # Native AAC uses indexed config 12 for 7.1, outside ADTS's 3-bit
    # field; force PCE so the fixture is a valid standalone ADTS stream.
    ("native71", "7.1", 8, ["-aac_pce", "1"]),
    ("pce51", "5.1", 6, ["-aac_pce", "1"]),
]:
    frequencies = [330, 440, 550, 80, 660, 770, 880, 990][:channels]
    expression = "|".join(f"0.08*sin(2*PI*{freq}*t)+if(lt(mod(t+0.021,0.06),0.003),0.08*sin(2*PI*{freq * 3}*t),0)"
                          for freq in frequencies)
    signal = f"aevalsrc='{expression}':s=48000:d=0.08:c={layout}"
    vector(name, ffmpeg(["-f", "lavfi", "-i", signal, "-c:a", "aac", "-b:a", "256k",
                        *flags, "-f", "adts", "pipe:1"]), channels)

source = (ROOT.parent / "libavcodec/aactab.c").read_text(encoding="utf-8")


def table(name):
    body = re.search(r"\b" + name + r"\s*\[[^]]*\]\s*=\s*\{([^}]+)\}", source).group(1)
    return [int(t.strip(), 0) for t in body.split(",") if t.strip()]


codes, lengths = table("codes5"), table("bits5")


class Frame:
    def __init__(self):
        self.bits = []

    def put(self, value, n):
        self.bits.extend((value >> i) & 1 for i in reversed(range(n)))

    def align(self):
        while len(self.bits) % 8:
            self.put(0, 1)

    def pce(self, groups, mixdown=False):
        self.put(5, 3)
        self.put(5, 4)  # nonzero PCE instance tag, independent of channel tags
        self.put(1, 2)  # AAC-LC
        self.put(3, 4)  # 48 kHz
        for group, width in zip(groups, [4, 4, 4, 2]):
            self.put(len(group), width)
        self.put(1 if mixdown else 0, 3)  # associated-data count
        self.put(0, 4)  # no coupling
        for size, value in [(4, 7), (4, 0), (3, 3)]:
            self.put(mixdown, 1)
            if mixdown:
                self.put(value, size)
        for group, entries in enumerate(groups):
            for kind, tag in entries:
                if group != 3:
                    self.put(kind, 1)
                self.put(tag, 4)
        if mixdown:
            self.put(3, 4)  # associated-data tag
        self.align()
        comment = b"layout-regression"
        self.put(len(comment), 8)
        for byte in comment:
            self.put(byte, 8)

    def channel(self, index, frame):
        self.put(176 + index * 2, 8)
        self.put(0, 1)
        self.put(0, 2)  # ONLY_LONG
        self.put((index + frame) % 2, 1)
        self.put(1, 6)
        self.put(0, 1)
        self.put(5, 4)
        self.put(1, 5)
        self.put(0, 1)  # scalefactor diff zero
        self.put(0, 3)  # pulse/TNS/gain control
        values = [[0, 1, -2, 3], [-3, 2, 1, 0], [4, -1, 0, -3], [-2, -1, 3, 1],
                  [1, 4, -3, -1], [2, -4, 1, 0]][index]
        for a, b in zip(values[::2], values[1::2]):
            row = (a + 4) * 9 + b + 4
            self.put(codes[row], lengths[row])

    def element(self, kind, tag, channel, frame):
        self.put(kind, 3)
        self.put(tag, 4)
        if kind == 1:
            self.put(0, 1)  # independent CPE windows
        self.channel(channel, frame)
        if kind == 1:
            self.channel(channel + 1, frame)

    def data_element(self, extended):
        self.put(4, 3)
        self.put(3, 4)
        self.put(extended, 1)  # align only the extended case
        self.put(255 if extended else 3, 8)
        if extended:
            self.put(5, 8)  # total count 260
            self.align()
        for i in range(260 if extended else 3):
            self.put(i % 256, 8)

    def finish(self):
        self.put(7, 3)
        self.align()
        payload = bytes(sum(self.bits[i + j] << (7 - j) for j in range(8))
                        for i in range(0, len(self.bits), 8))
        size = len(payload) + 7
        return bytes([0xff, 0xf1, 0x4c, (size >> 11), (size >> 3) & 255,
                      ((size & 7) << 5) | 0x1f, 0xfc]) + payload  # config=0, PCE


stream = []
for i in range(4):
    frame = Frame()
    if i == 0:
        frame.pce([[(0, 7), (0, 11)], [], [], []], mixdown=True)
    frame.data_element(i == 0)
    for tag in ([11, 7] if i % 2 == 0 else [7, 11]):
        frame.element(0, tag, 0 if tag == 7 else 1, i)
    stream.append(frame.finish())
vector("tagged_dual", b"".join(stream), 2)

stream = []
elements = [(0, 0, 2), (1, 0, 0), (1, 1, 4), (3, 0, 3)]
for i in range(4):
    frame = Frame()
    if i == 0:
        frame.pce([[(0, 0), (1, 0)], [], [(1, 1)], [(3, 0)]])
    for index in ([2, 3, 0, 1] if i % 2 == 0 else [1, 0, 3, 2]):
        kind, tag, channel = elements[index]
        frame.element(kind, tag, channel, i)
    stream.append(frame.finish())
vector("shuffled51", b"".join(stream), 6)

