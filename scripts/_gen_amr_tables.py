"""Generate libavcodec/amr_tables.mbt from the FFmpeg 9.0.2 AMR-NB sources.

Run from the moonbit/ directory:
    python scripts/_gen_amr_tables.py
The FFmpeg tree is expected at ../.scratch/FFmpeg-n9.0.2 (repository scratch).
"""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, ".scratch", "FFmpeg-n9.0.2", "libavcodec")
OUT = os.path.join(ROOT, "libavcodec", "amr_tables.mbt")


def read(name):
    with open(os.path.join(SRC, name), "r", encoding="utf-8") as f:
        text = f.read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def extract_block(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*\[[^=;]*=\s*\{", text)
    if not m:
        raise SystemExit("array not found: " + name)
    i = m.end() - 1
    depth = 0
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[m.end():i]
        i += 1
    raise SystemExit("unterminated array: " + name)


def numbers(block):
    return [int(x, 0) for x in re.findall(r"0x[0-9a-fA-F]+|-?\d+", block)]


def floats(block):
    return [float(x) for x in re.findall(
        r"-?(?:\d+\.\d*|\.\d+|\d+)(?:[eE][-+]?\d+)?", block)]


def rows(block):
    out = []
    depth = 0
    start = None
    for i, c in enumerate(block):
        if c == "{":
            if depth == 0:
                start = i + 1
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                out.append(block[start:i])
    return out


def flat(text, name):
    return numbers(extract_block(text, name))


def order_values(text, name):
    """Expand AMR_BIT()/AMR_OF() to byte offsets before reading numbers."""
    block = extract_block(text, name)

    def bit_lsf(m):
        return str(2 * int(m.group(1)))

    def of_pulse(m):
        return str((5 + 13 * int(m.group(1)) + 3 + int(m.group(2))) * 2)

    def of_field(m):
        base = {"p_lag": 0, "p_gain": 1, "fixed_gain": 2}[m.group(2)]
        return str((5 + 13 * int(m.group(1)) + base) * 2)

    block = re.sub(r"AMR_BIT\(\s*lsf\[(\d+)\]\s*\)", bit_lsf, block)
    block = re.sub(r"AMR_OF\(\s*(\d+)\s*,\s*pulses\[(\d+)\]\s*\)",
                   of_pulse, block)
    block = re.sub(
        r"AMR_OF\(\s*(\d+)\s*,\s*(p_lag|p_gain|fixed_gain)\s*\)",
        of_field, block)
    assert "AMR_" not in block, block[:200]
    return numbers(block)


def flat_f(text, name):
    return floats(extract_block(text, name))


def flat2(text, name):
    out = []
    for row in rows(extract_block(text, name)):
        out.extend(numbers(row))
    return out


def scalar_f(text, name):
    m = re.search(r"\b" + re.escape(name) + r"\s*=\s*([-0-9.eE+]+)\s*;", text)
    if not m:
        raise SystemExit("scalar not found: " + name)
    return float(m.group(1))


def fmt_int(values, indent="  ", width=100):
    lines = []
    cur = indent
    for v in values:
        add = str(v) + ", "
        if len(cur) + len(add) > width:
            lines.append(cur.rstrip())
            cur = indent + add
        else:
            cur += add
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def fmt_float(values, indent="  ", width=96):
    lines = []
    cur = indent
    for v in values:
        add = repr(float(v)) + ", "
        if len(cur) + len(add) > width:
            lines.append(cur.rstrip())
            cur = indent + add
        else:
            cur += add
    if cur.strip():
        lines.append(cur.rstrip())
    return "\n".join(lines)


def emit_int(name, values, comment):
    return "///|\n/// %s\nlet %s : FixedArray[Int32] = [\n%s\n]\n" % (
        comment, name, fmt_int(values))


def emit_float(name, values, comment):
    return "///|\n/// %s\nlet %s : FixedArray[Double] = [\n%s\n]\n" % (
        comment, name, fmt_float(values))


amr = read("amrnbdata.h")
acelp = read("acelp_vectors.c")

order_names = ["order_MODE_4k75", "order_MODE_5k15", "order_MODE_5k9",
               "order_MODE_6k7", "order_MODE_7k4", "order_MODE_7k95",
               "order_MODE_10k2", "order_MODE_12k2"]
parts = ["""///|
/// AMR-NB tables extracted from FFmpeg 9.0.2 `libavcodec/amrnbdata.h` and
/// `acelp_vectors.c`; generated by `scripts/_gen_amr_tables.py`.
///
/// Original FFmpeg code is LGPL-2.1-or-later; this port keeps the same license.
"""]

for name in order_names:
    vals = order_values(amr, name)
    assert vals and vals[-1] == 0, name
    parts.append(emit_int("amr_" + name.lower(), vals,
                          "`%s` (unpacking order, 0-terminated)." % name))

parts.append(emit_int("amr_frame_sizes_nb", flat(amr, "frame_sizes_nb"),
                      "`frame_sizes_nb`: speech payload bytes per mode."))
parts.append(emit_int("amr_base_five_table", flat2(amr, "base_five_table"),
                      "`base_five_table[128][3]` flattened."))
parts.append(emit_int("amr_lsp_sub4_init", flat(amr, "lsp_sub4_init"),
                      "`lsp_sub4_init` (Q15 / 1000)."))
parts.append(emit_int("amr_lsp_avg_init", flat(amr, "lsp_avg_init"),
                      "`lsp_avg_init` (Q15)."))

for name, comment in [
    ("lsf_3_3_MODE_5k15", "5.15 kbit/s 3-split LSF codebook [128][4]."),
    ("lsf_3_1_MODE_7k95", "7.95 kbit/s 3-split LSF codebook [512][3]."),
    ("lsf_3_1", "3-split LSF codebook 1 [256][3]."),
    ("lsf_3_2", "3-split LSF codebook 2 [512][3]."),
    ("lsf_3_3", "3-split LSF codebook 3 [512][4]."),
    ("lsf_5_1", "12.2 kbit/s 5-split LSF codebook 1 [128][4]."),
    ("lsf_5_2", "12.2 kbit/s 5-split LSF codebook 2 [256][4]."),
    ("lsf_5_3", "12.2 kbit/s 5-split LSF codebook 3 [256][4]."),
    ("lsf_5_4", "12.2 kbit/s 5-split LSF codebook 4 [256][4]."),
    ("lsf_5_5", "12.2 kbit/s 5-split LSF codebook 5 [64][4]."),
]:
    parts.append(emit_int("amr_" + name, flat2(amr, name),
                          "`%s` %s" % (name, comment)))

for name, comment in [
    ("lsf_3_mean", "`lsf_3_mean`."),
    ("lsf_5_mean", "`lsf_5_mean`."),
    ("pred_fac", "`pred_fac`."),
]:
    parts.append(emit_float("amr_" + name, flat_f(amr, name), comment))

parts.append(emit_int("amr_track_position", flat(amr, "track_position"),
                      "`track_position`."))
parts.append(emit_int("amr_gray_decode", flat(amr, "gray_decode"),
                      "`gray_decode`."))
parts.append(emit_int("amr_qua_gain_pit", flat(amr, "qua_gain_pit"),
                      "`qua_gain_pit`."))
parts.append(emit_int("amr_qua_gain_code", flat(amr, "qua_gain_code"),
                      "`qua_gain_code`."))
parts.append(emit_float("amr_energy_mean", flat_f(amr, "energy_mean"),
                        "`energy_mean`."))
parts.append(emit_float("amr_energy_pred_fac", flat_f(amr, "energy_pred_fac"),
                        "`energy_pred_fac`."))
parts.append(emit_int("amr_gains_mode_4k75", flat2(amr, "gains_MODE_4k75"),
                      "`gains_MODE_4k75[512][2]` flattened."))
parts.append(emit_int("amr_gains_high", flat2(amr, "gains_high"),
                      "`gains_high[128][2]` flattened."))
parts.append(emit_int("amr_gains_low", flat2(amr, "gains_low"),
                      "`gains_low[64][2]` flattened."))
parts.append(emit_float("amr_ir_filter_strong_mode_795",
                        flat_f(amr, "ir_filter_strong_MODE_7k95"),
                        "`ir_filter_strong_MODE_7k95`."))
parts.append(emit_float("amr_ir_filter_strong", flat_f(amr, "ir_filter_strong"),
                        "`ir_filter_strong`."))
parts.append(emit_float("amr_ir_filter_medium", flat_f(amr, "ir_filter_medium"),
                        "`ir_filter_medium`."))
parts.append(emit_float("amr_highpass_zeros", flat_f(amr, "highpass_zeros"),
                        "`highpass_zeros`."))
parts.append(emit_float("amr_highpass_poles", flat_f(amr, "highpass_poles"),
                        "`highpass_poles`."))
parts.append(emit_float("amr_highpass_gain", [scalar_f(amr, "highpass_gain")],
                        "`highpass_gain`."))
parts.append(emit_float("amr_b60_sinc", flat_f(acelp, "ff_b60_sinc"),
                        "`ff_b60_sinc` (60th-order Hamming windowed sinc)."))
parts.append(emit_float("amr_pow_0_7", flat_f(acelp, "ff_pow_0_7"),
                        "`ff_pow_0_7`."))
parts.append(emit_float("amr_pow_0_75", flat_f(acelp, "ff_pow_0_75"),
                        "`ff_pow_0_75`."))
parts.append(emit_float("amr_pow_0_55", flat_f(acelp, "ff_pow_0_55"),
                        "`ff_pow_0_55`."))

text = "\n".join(parts)
assert len(text) > 20000
with open(OUT + ".new", "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
os.replace(OUT + ".new", OUT)
print("wrote", OUT, len(text), "bytes")
print("orders", [len(order_values(amr, n)) for n in order_names])
print("lsf sizes", len(flat2(amr, "lsf_3_3")), len(flat2(amr, "lsf_5_2")))
