"""AAC-LC stereo references from Docker linuxserver/ffmpeg:9.0.2.

Real native/FDK streams exercise stereo decisions. Synthetic streams
cover independent windows and each M/S/intensity branch explicitly.
Expected PCM is always FFmpeg decoding the same encoded bytes.
"""
import base64
from pathlib import Path
import re
import subprocess
import textwrap

ROOT = Path(__file__).resolve().parents[1]
IMAGE = "linuxserver/ffmpeg:9.0.2"
SIGNAL = (
    "aevalsrc='0.12*sin(2*PI*440*t)+0.08*sin(2*PI*6000*t)+"
    "if(lt(mod(t+0.021,0.06),0.003),0.5*sin(2*PI*3300*t),0)|"
    "0.1*sin(2*PI*660*t)+0.06*sin(2*PI*6000*t)+"
    "if(lt(mod(t+0.021,0.06),0.003),0.4*sin(2*PI*3300*t),0)':s=48000:d=0.18"
)


def ffmpeg(args, data=None):
    result = subprocess.run(
        ["docker", "run", "--rm", "-i", IMAGE, "-v", "error", *args],
        input=data, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60,
    )
    if result.returncode:
        raise RuntimeError(result.stderr.decode("utf-8", errors="replace"))
    return result.stdout


def emit(name, data):
    chunks = textwrap.wrap(base64.b64encode(data).decode("ascii"), 112)
    return "///|\nlet " + name + " : Bytes = " + " +\n  ".join('b"' + c + '"' for c in chunks) + "\n"


lines = ["///|\n/// Stereo AAC-LC references generated by scripts/generate_aac_stereo_vectors.py.",
         "/// Docker linuxserver/ffmpeg:9.0.2; PCM is interleaved s16le.",
         "/// Real encoder inputs/options and synthetic syntax are recorded in the script.",
         "/// LGPL-2.1-or-later.\n"]


def vector(name, encoded):
    pcm = ffmpeg(["-i", "pipe:0", "-f", "s16le", "pipe:1"], encoded)
    lines.append(f"/// {name}: {len(encoded)} ADTS bytes, {len(pcm) // 4096} stereo frames.\n")
    lines.append(emit("aac_stereo_" + name + "_b64", encoded))
    lines.append(emit("aac_stereo_" + name + "_pcm_b64", pcm))
    print(name, "ADTS bytes", len(encoded), "stereo frames", len(pcm) // 4096)


for name, encoder, bitrate, flags in [
    ("native", "aac", "96k", ["-aac_ms", "1", "-aac_is", "1", "-aac_tns", "1", "-aac_pns", "1"]),
    ("fdk", "libfdk_aac", "48k", []),
]:
    vector(name, ffmpeg(["-f", "lavfi", "-i", SIGNAL, "-ac", "2", "-c:a", encoder,
                        "-profile:a", "aac_low", "-b:a", bitrate, *flags, "-f", "adts", "pipe:1"]))

source = (ROOT.parent / "libavcodec/aactab.c").read_text(encoding="utf-8")


def table(name):
    body = re.search(r"\b" + name + r"\s*\[[^]]*\]\s*=\s*\{([^}]+)\}", source).group(1)
    return [int(t.strip(), 0) for t in body.split(",") if t.strip()]


sf_codes, sf_bits = table("ff_aac_scalefactor_code"), table("ff_aac_scalefactor_bits")
codes, bits = table("codes5"), table("bits5")


class Frame:
    def __init__(self):
        self.bits = []
        self.put(1, 3)  # CPE
        self.put(0, 4)  # instance tag

    def put(self, value, n):
        self.bits.extend((value >> i) & 1 for i in reversed(range(n)))

    def info(self, sequence, shape, bands):
        self.put(0, 1)
        self.put(sequence, 2)
        self.put(shape, 1)
        if sequence == 2:
            self.put(bands, 4)
            self.put(127, 7)  # one group of eight windows
        else:
            self.put(bands, 6)
            self.put(0, 1)

    def channel(self, sequence, shape, books, values, common=False, gain=180):
        self.put(gain, 8)
        if not common:
            self.info(sequence, shape, len(books))
        for book in books:
            self.put(book, 4)
            self.put(1, 3 if sequence == 2 else 5)
        for book in books:
            if book == 13:
                self.put(256, 9)
            elif book:
                row = 64 if book in (14, 15) else 60
                self.put(sf_codes[row], sf_bits[row])
        self.put(0, 3)  # pulse/TNS/gain control absent
        for band, book in enumerate(books):
            if book == 5:
                for _ in range(8 if sequence == 2 else 1):
                    q = values[band]
                    for first, second in zip(q[::2], q[1::2]):
                        row = (first + 4) * 9 + second + 4
                        self.put(codes[row], bits[row])

    def finish(self):
        self.put(7, 3)
        while len(self.bits) % 8:
            self.put(0, 1)
        payload = bytes(sum(self.bits[i + j] << (7 - j) for j in range(8))
                        for i in range(0, len(self.bits), 8))
        size = len(payload) + 7
        # ADTS: AAC-LC, 48 kHz, stereo, no CRC, one raw_data_block.
        return bytes([0xff, 0xf1, 0x4c, 0x80 | (size >> 11), (size >> 3) & 255,
                      ((size & 7) << 5) | 0x1f, 0xfc]) + payload


stream = []
for i, (left, right) in enumerate(zip([0, 1, 2, 3, 0], [1, 2, 3, 0, 0])):
    frame = Frame()
    frame.put(0, 1)  # independent window syntax
    frame.channel(left, i % 2, [5], [[0, 1, -2, 3]])
    frame.channel(right, 1 - i % 2, [5], [[-3, 2, 1, 0]], gain=172)
    stream.append(frame.finish())
vector("independent", b"".join(stream))

stream = []
# (M/S mode, explicit two-band mask, left second book, right second book).
for i, (mode, mask, left_book, right_book) in enumerate([
    (0, [0, 0], 5, 5), (1, [1, 0], 5, 5), (2, [1, 1], 5, 5),
    (0, [0, 0], 5, 14), (1, [0, 1], 5, 14), (2, [1, 1], 5, 15),
    (0, [0, 0], 5, 15), (2, [1, 1], 13, 5), (2, [1, 1], 5, 13),
]):
    frame = Frame()
    frame.put(1, 1)
    frame.info(0, i % 2, 2)
    frame.put(mode, 2)
    if mode == 1:
        for bit in mask:
            frame.put(bit, 1)
    frame.channel(0, i % 2, [5, left_book], [[0, 1, -2, 3], [4, -1, 0, -3]], common=True)
    frame.channel(0, i % 2, [5, right_book], [[-3, 2, 1, 0], [1, -4, 2, 0]], common=True, gain=176)
    stream.append(frame.finish())
vector("joint", b"".join(stream))

(ROOT / "libavcodec/aac_stereo_realdata_wbtest.mbt").write_text("\n".join(lines), encoding="utf-8", newline="\n")
